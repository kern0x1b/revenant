local VERSION = "2"

local sdk = import("sdk", {anonymous = true})

local LAYOUT = {
    VERSION = VERSION,
    SOURCES_ROOT = "../frameworks/Backports/src",
    SNAP_ROOT = "packages/frameworks/apple-backports/spec",
    OUT_ROOT = "packages/frameworks/apple-backports/.gen",
    PINS_ROOT = "packages/frameworks/apple-backports/overrides/hashes",
    PROTOCOL_SETS_ROOT = "packages/frameworks/apple-backports/overrides/protocol-sets",
    REGISTRY = "packages/frameworks/apple-backports/registry",
    MARK = "// GENERATED by tools/gen.lua version " .. VERSION .. ". Do not edit. Regenerate: xmake l tools/gen.lua gen.",
    SHARD_FILE = "declarations.tsv",
    SPEC_COLUMNS = {"kind", "api", "cls", "key", "introduced", "type", "availability", "hash", "value_status", "value",
                    "host_value", "value_source", "owned", "tbd", "shape", "measured"},
    PIN_COLUMNS = {"api", "key", "pinned", "pinned-by", "registry"},
}

function constants()
    return LAYOUT
end

function snap_dir(tree, fw)
    return path.join(tree, LAYOUT.SNAP_ROOT, fw)
end

function shard_path(tree, fw)
    return path.join(snap_dir(tree, fw), LAYOUT.SHARD_FILE)
end

function constant_record_path(tree, fw)
    return path.join(snap_dir(tree, fw), "constants.tsv")
end

function gen_dir(tree, fw)
    return path.join(tree, LAYOUT.OUT_ROOT, fw)
end

function spec_path(tree, fw, sdk_release)
    return path.join(gen_dir(tree, fw), "spec." .. sdk.names(sdk_release).sdk_id .. ".tsv")
end

function pins_path(tree, fw)
    return path.join(tree, LAYOUT.PINS_ROOT, fw .. ".tsv")
end

function protocol_set_path(tree, fw)
    return path.join(tree, LAYOUT.PROTOCOL_SETS_ROOT, fw .. ".tsv")
end

function manifest_path(tree, fw)
    return path.join(gen_dir(tree, fw), "manifest.tsv")
end

function members_path(tree, fw)
    return path.join(gen_dir(tree, fw), "members.tsv")
end

function registry_dir(fw)
    return path.join(LAYOUT.REGISTRY, fw)
end
