rule("rn-codegen")
    on_config(function (target)
        import("core.project.project")
        import("core.base.json")
        local tool = project.required_package("react-native-codegen"):installdir()
        local node = path.join(project.required_package("node"):installdir(), "bin", "node")
        local library = project.required_package(target:values("rn.codegen.library"))
        local manifest = json.decode(io.readfile(path.join(library:installdir(), "package.json")))
        local work = path.join(target:autogendir(), "rn-codegen")
        os.rm(work)
        local runtime = path.join(work, "runtime")
        os.mkdir(runtime)
        os.vcp(path.join(tool, "*"), runtime .. "/")
        local app = path.join(work, "app")
        os.mkdir(path.join(app, "node_modules"))
        io.writefile(path.join(app, "package.json"), json.encode({name = "app", private = true,
            dependencies = {[manifest.name] = manifest.version, ["react-native"] = "0.86.3"}}))
        os.ln(library:installdir(), path.join(app, "node_modules", manifest.name))
        os.ln(path.join(runtime, "react-native"), path.join(app, "node_modules", "react-native"))
        local output = path.join(work, "out")
        os.vrunv(node, {path.join(runtime, "react-native", "scripts", "generate-codegen-artifacts.js"), "-p", app, "-t", "ios",
                        "-o", output, "-s", "library"})
        target:data_set("rn.codegen.output", path.join(output, "build", "generated", "ios", "ReactCodegen"))
    end)
