set_project("swift-crypto-shared")
set_version("0.0.1")
local root = os.getenv("SWIFT_CRYPTO_ROOT") or path.join(os.scriptdir(), "../../..")
add_repositories("revenant " .. root)
add_addons("revenant v0.8.17")
set_config("apple_minimum", "6.0")
includes("@addon/revenant/apple-ios")
set_allowedplats("iphoneos")
set_allowedarchs("iphoneos|armv7")
set_defaultplat("iphoneos")
set_defaultarchs("iphoneos|armv7")
add_requires("revenant@swift-runtime", {alias = "swift-runtime", configs = {shared = true}})
add_requires("revenant@libcxx", {alias = "libcxx", configs = {packaged = true}})
add_requireconfs("**.libcxx", {configs = {packaged = true}})
add_requires("revenant@swift-crypto", {alias = "swift-crypto", configs = {shared = true}})

target("probe")
    set_kind("phony")
    add_packages("swift-crypto")
    on_config(function (target)
        io.writefile(os.getenv("SWIFT_CRYPTO_PROBE"), target:pkg("swift-crypto"):installdir())
    end)
