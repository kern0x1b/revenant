set_project("emulatefontapp")
set_version("0.0.1")
local REVENANT = os.getenv("REVENANT_REPO") or path.absolute(path.join(os.scriptdir(), "../../../.."))
add_repositories("revenant " .. REVENANT)
add_addons("revenant", {sourcedir = path.join(REVENANT, "toolchain")})
set_config("apple_minimum", "6.1.3")
includes("@addon/revenant/apple-ios")
includes("@addon/revenant/emulate")
set_allowedplats("iphoneos")
set_allowedarchs("iphoneos|armv7")
set_defaultplat("iphoneos")
set_defaultarchs("iphoneos|armv7")

target("emulatefontapp")
    add_rules("@addon/revenant/app")
    add_files("main.m")
    add_frameworks("Foundation", "UIKit", "CoreGraphics")
    set_values("app.plist-file", "Info.plist")
    set_values("revenant.version", "1.0")
    set_values("revenant.control", "control")
