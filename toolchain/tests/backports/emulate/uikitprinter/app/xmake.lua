set_project("revenantuikitprinterapp")
set_version("0.0.1")
local root = os.getenv("CHARUIKITPRINTER_ROOT") or path.join(os.scriptdir(), "../../../../..")
add_repositories("revenant " .. root)
add_addons("revenant v0.8.17")
set_config("apple_minimum", os.getenv("CHARUIKITPRINTER_MINIMUM") or "6.1.3")
add_requires("revenant@apple-backports", {alias = "apple-backports", configs = {uikit = true}})
includes("@addon/revenant/apple-ios")
includes("@addon/revenant/emulate")
set_defaultplat("iphoneos")
set_defaultarchs("iphoneos|armv7")

target("revenantuikitprinterapp")
    add_rules("@addon/revenant/app")
    add_files(path.join(root, "tests/backports/emulate/uikitprinter/app/main.m"))
    add_mflags("-fobjc-arc")
    add_ldflags("-fobjc-arc", {force = true})
    add_frameworks("Foundation", "UIKit")
    add_packages("apple-backports")
    set_values("revenant.libraries", "apple-backports")
    set_values("app.plist-file", "Info.plist")
    set_values("revenant.control", "control")
