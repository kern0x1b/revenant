local names = { "SRAbsoluteTimeGetCurrent", "SRAbsoluteTimeFromContinuousTime",
    "SRAbsoluteTimeToCFAbsoluteTime", "SRAbsoluteTimeFromCFAbsoluteTime",
    "dateWithSRAbsoluteTime", "initWithSRAbsoluteTime", "srAbsoluteTime" }

function main(registry, out)
    local handle = assert(io.open(out, "w"))
    handle:write("// Generated by rename.lua: the port's four time functions, under names of their own.\n")
    for _, name in ipairs(names) do
        handle:write(string.format("#define %s Charon%s\n", name, name))
    end
    handle:close()
end
