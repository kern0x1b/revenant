local V = import("vtlib", {rootdir = os.scriptdir()})

local CLASSES = {
    "VTFrameProcessor", "VTFrameProcessorFrame", "VTFrameProcessorOpticalFlow",
    "VTFrameRateConversionConfiguration", "VTFrameRateConversionParameters",
    "VTLowLatencyFrameInterpolationConfiguration", "VTLowLatencyFrameInterpolationParameters",
    "VTLowLatencySuperResolutionScalerConfiguration", "VTLowLatencySuperResolutionScalerParameters",
    "VTMotionBlurConfiguration", "VTMotionBlurParameters", "VTOpticalFlowConfiguration",
    "VTOpticalFlowParameters", "VTSuperResolutionScalerConfiguration",
    "VTSuperResolutionScalerParameters", "VTTemporalNoiseFilterConfiguration",
    "VTTemporalNoiseFilterParameters",
}

function main(out_path)
    if out_path == nil then
        V.fail("rename.lua: usage: rename.lua OUT.h")
    end
    local lines = {"// Generated by rename.py: the port's own declarations, under names of their own.\n"}
    for _, name in ipairs(CLASSES) do
        lines[#lines + 1] = string.format("#define %s Revenant%s\n", name, name)
    end
    local parent = string.match(out_path, "^(.*)/[^/]*$")
    if parent and parent ~= "" and not os.isdir(parent) then
        V.fail("rename.lua: cannot write " .. out_path .. ": no such directory " .. parent)
    end
    try {
        function()
            V.write_file(out_path, table.concat(lines))
        end,
        catch {
            function(err)
                V.fail("rename.lua: cannot write " .. out_path .. ": " .. tostring(err))
            end
        }
    }
end
