local function hexwords(text)
    local values = {}
    local i = 1
    while i <= #text do
        local group = text:sub(i, i + 7)
        if #group ~= 8 or not group:find("^[0-9A-F]+$") then
            return nil
        end
        values[#values + 1] = tonumber(group, 16)
        i = i + 8
        if text:sub(i, i) == " " then
            i = i + 1
        end
    end
    if #values == 0 then
        return nil
    end
    return values
end

local function parse(path)
    local rows = {}
    local label = nil
    local words = nil
    for raw in io.lines(path) do
        local line = raw:gsub("^%s+", ""):gsub("%s+$", "")
        local labelText, wordText = line:match("^(.-) in: (.*)$")
        local jrWord = line:match("^in ([0-9A-F]+)$")
        local bytesText = line:match("bytes=([0-9A-F]+)$")
        local listed = labelText and hexwords(wordText)
        if listed then
            label = labelText
            words = listed
        elseif jrWord and #jrWord == 8 then
            label = "jr"
            words = {tonumber(jrWord, 16)}
        elseif bytesText and (line:sub(1, 3) == "ts=" or line:sub(1, 5) == "type=") then
            local values = {}
            for i = 1, #bytesText, 2 do
                values[#values + 1] = tonumber(bytesText:sub(i, i + 1), 16)
            end
            for i = #values + 1, 28 do
                values[i] = 0
            end
            rows[#rows + 1] = {label, words, values}
        end
    end
    return rows
end

function main(outPath)
    local rows = {}
    for _, row in ipairs(parse("visit-macos.txt")) do
        rows[#rows + 1] = row
    end
    for _, row in ipairs(parse("visit-jr.txt")) do
        rows[#rows + 1] = row
    end
    local h = assert(io.open(outPath, "w"))
    h:write("// Generated by oracle/visit-expectations.lua from the macOS visitor (oracle/visit.m, visit-jr.txt). Do not edit.\n")
    h:write("typedef struct revenant_visit_case {\n    const char *label;\n    unsigned int words[4];\n    int wordCount;\n")
    h:write("    unsigned char bytes[28];\n} revenant_visit_case;\n\n")
    h:write("static const revenant_visit_case revenant_visit_cases[] = {\n")
    for _, row in ipairs(rows) do
        local label, words, bytes = row[1], row[2], row[3]
        local padded = {}
        for i = 1, 4 do
            padded[i] = string.format("0x%08Xu", words[i] or 0)
        end
        local byteText = {}
        for i, b in ipairs(bytes) do
            byteText[i] = string.format("0x%02X", b)
        end
        h:write(string.format('    {"%s", {%s}, %d, {%s}},\n', label, table.concat(padded, ", "), #words, table.concat(byteText, ", ")))
    end
    h:write("};\n")
    h:close()
    print(string.format("cases=%d", #rows))
end
