static void test_unknown_attributes(void)
{
    UIView *root = [[UIView alloc] initWithFrame:CGRectMake(0, 0, 320, 480)];
    UIView *child = [[UIView alloc] initWithFrame:CGRectMake(1, 2, 3, 4)];
    child.translatesAutoresizingMaskIntoConstraints = NO;
    [root addSubview:child];
    NSLayoutConstraint *margin = [NSLayoutConstraint constraintWithItem:child attribute:NSLayoutAttributeLeadingMargin relatedBy:NSLayoutRelationEqual toItem:root attribute:NSLayoutAttributeTop multiplier:1 constant:100];
    CHECK(margin.firstAttribute == NSLayoutAttributeLeadingMargin, "iOS 6 accepts a constraint with an iOS 8 attribute");
    BOOL raised = NO;
    @try {
        [margin description];
    } @catch (NSException *exception) {
        raised = YES;
    }
    printf("description of an iOS 8 attribute constraint raises: %d\n", raised);
    [root addConstraint:margin];
    [root addConstraint:[NSLayoutConstraint constraintWithItem:child attribute:NSLayoutAttributeHeight relatedBy:NSLayoutRelationEqual toItem:nil attribute:NSLayoutAttributeNotAnAttribute multiplier:1 constant:20]];
    [root layoutIfNeeded];
    printf("frame under an iOS 8 attribute constraint: %s\n", NSStringFromCGRect(child.frame).UTF8String);
    UIStackView *stack = [[UIStackView alloc] initWithArrangedSubviews:@[label(@"one", 20), sized(10, 30), label(@"two", 12)]];
    stack.axis = UILayoutConstraintAxisVertical;
    stack.baselineRelativeArrangement = YES;
    stack.layoutMarginsRelativeArrangement = YES;
    UIStackView *row = [[UIStackView alloc] initWithArrangedSubviews:@[label(@"a", 20), stack, sized(4, 4)]];
    row.alignment = UIStackViewAlignmentFirstBaseline;
    UIView *holder = [[UIView alloc] initWithFrame:CGRectMake(0, 0, 320, 480)];
    [holder addSubview:row];
    NSLayoutAnchor *anchor = row.firstBaselineAnchor;
    [NSLayoutConstraint activateConstraints:@[[anchor constraintEqualToAnchor:holder.topAnchor constant:40], [row.leftAnchor constraintEqualToAnchor:holder.leftAnchor]]];
    row.translatesAutoresizingMaskIntoConstraints = NO;
    layout_tree(holder);
    BOOL known = YES;
    NSMutableArray *pending = [NSMutableArray arrayWithObject:holder];
    while (pending.count) {
        UIView *view = [pending lastObject];
        [pending removeLastObject];
        [pending addObjectsFromArray:view.subviews];
        for (NSLayoutConstraint *constraint in view.constraints) {
            if (constraint.firstAttribute > NSLayoutAttributeBaseline || constraint.secondAttribute > NSLayoutAttributeBaseline)
                known = NO;
        }
    }
    CHECK(known, "stack views, anchors and layout guides only create attributes iOS 6 knows");
}

static void test_activation(void)
{
    UIView *root = [[UIView alloc] initWithFrame:CGRectMake(0, 0, 300, 300)];
    UIView *left = [UIView new], *right = [UIView new], *leftChild = [UIView new], *rightChild = [UIView new], *loner = [UIView new];
    [root addSubview:left];
    [root addSubview:right];
    [left addSubview:leftChild];
    [right addSubview:rightChild];
    NSArray *cases = @[@[leftChild, rightChild, root], @[leftChild, left, left], @[left, leftChild, left], @[leftChild, root, root], @[left, right, root], @[rightChild, [NSNull null], rightChild]];
    for (NSArray *item in cases) {
        id second = [item objectAtIndex:1] == [NSNull null] ? nil : [item objectAtIndex:1];
        UIView *expected = [item objectAtIndex:2];
        NSLayoutConstraint *constraint = [NSLayoutConstraint constraintWithItem:[item objectAtIndex:0] attribute:NSLayoutAttributeWidth relatedBy:NSLayoutRelationEqual toItem:second attribute:second ? NSLayoutAttributeWidth : NSLayoutAttributeNotAnAttribute multiplier:1 constant:5];
        CHECK(!constraint.active, "a new constraint is inactive");
        constraint.active = YES;
        CHECK([expected.constraints indexOfObjectIdenticalTo:constraint] != NSNotFound, "activation installs on the nearest common ancestor");
        CHECK(constraint.active, "an installed constraint is active");
        constraint.active = YES;
        NSUInteger installed = 0;
        for (NSLayoutConstraint *other in expected.constraints)
            installed += other == constraint;
        CHECK(installed == 1, "activating twice installs once");
        constraint.active = NO;
        CHECK(!constraint.active && [expected.constraints indexOfObjectIdenticalTo:constraint] == NSNotFound, "deactivation removes the constraint");
    }
    NSLayoutConstraint *added = [NSLayoutConstraint constraintWithItem:leftChild attribute:NSLayoutAttributeLeft relatedBy:NSLayoutRelationEqual toItem:root attribute:NSLayoutAttributeLeft multiplier:1 constant:0];
    [root addConstraint:added];
    CHECK(added.active, "a constraint added with addConstraint: reports active");
    NSLayoutConstraint *other = [NSLayoutConstraint constraintWithItem:left attribute:NSLayoutAttributeTop relatedBy:NSLayoutRelationEqual toItem:root attribute:NSLayoutAttributeTop multiplier:1 constant:0];
    [NSLayoutConstraint deactivateConstraints:@[added]];
    [NSLayoutConstraint activateConstraints:@[other]];
    CHECK(!added.active && other.active, "activateConstraints and deactivateConstraints");
    NSString *name = nil;
    NSLayoutConstraint *orphan = [NSLayoutConstraint constraintWithItem:loner attribute:NSLayoutAttributeLeft relatedBy:NSLayoutRelationEqual toItem:root attribute:NSLayoutAttributeLeft multiplier:1 constant:0];
    @try {
        orphan.active = YES;
    } @catch (NSException *exception) {
        name = exception.name;
    }
    CHECK_EQUAL(name, NSGenericException, "activating without a common ancestor raises NSGenericException");

    UIView *top = [UIView new];
    UIView *member = [UIView new];
    [top addSubview:member];
    UILayoutGuide *guide = [UILayoutGuide new];
    NSLayoutConstraint *ownerless = [guide.widthAnchor constraintEqualToConstant:5];
    ownerless.active = YES;
    CHECK(!ownerless.active, "a guide without an owner takes no constraint");
    [top addLayoutGuide:guide];
    NSLayoutConstraint *pair = [guide.leadingAnchor constraintEqualToAnchor:member.leadingAnchor];
