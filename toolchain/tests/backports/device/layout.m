        [t insertArrangedSubview:[UIView new] atIndex:5];
    } @catch (NSException *exception) {
        name = exception.name;
    }
    CHECK_EQUAL(name, NSInvalidArgumentException, "inserting past the end raises");
    [t removeArrangedSubview:foreign];
    [t removeArrangedSubview:b];
    CHECK(t.arrangedSubviews.count == 2 && b.superview == t, "removeArrangedSubview keeps the subview");
    [c removeFromSuperview];
    CHECK(t.arrangedSubviews.count == 1, "removeFromSuperview removes the arranged view");
    UIStackView *u = [[UIStackView alloc] initWithFrame:CGRectZero];
    [u addArrangedSubview:a];
    CHECK(t.arrangedSubviews.count == 0 && u.arrangedSubviews.count == 1 && a.superview == u, "adding to another stack moves the view");
    UIStackView *coded = [[UIStackView alloc] initWithArrangedSubviews:@[sized(20, 20), label(@"coded", 14)]];
    coded.axis = UILayoutConstraintAxisVertical;
    coded.distribution = UIStackViewDistributionEqualSpacing;
    coded.alignment = UIStackViewAlignmentTrailing;
    coded.spacing = 7;
    coded.baselineRelativeArrangement = YES;
    coded.layoutMarginsRelativeArrangement = YES;
    coded.layoutMargins = UIEdgeInsetsMake(1, 2, 3, 4);
    UIStackView *decoded = [NSKeyedUnarchiver unarchiveObjectWithData:[NSKeyedArchiver archivedDataWithRootObject:coded]];
    CHECK([decoded isKindOfClass:[UIStackView class]] && decoded.axis == coded.axis && decoded.distribution == coded.distribution && decoded.alignment == coded.alignment && decoded.spacing == 7 && decoded.baselineRelativeArrangement && decoded.layoutMarginsRelativeArrangement, "NSCoding keeps stack properties");
    CHECK(decoded.arrangedSubviews.count == 2 && [[decoded.arrangedSubviews objectAtIndex:1] isKindOfClass:[UILabel class]] && UIEdgeInsetsEqualToEdgeInsets(decoded.layoutMargins, UIEdgeInsetsMake(1, 2, 3, 4)), "NSCoding keeps arranged subviews and margins");

    UIView *root = [[UIView alloc] initWithFrame:CGRectMake(0, 0, 320, 480)];
    UILabel *big = label(@"Big", 30), *small = label(@"small", 11);
    UILabel *innerText = label(@"inner", 17);
    UIStackView *inner = [[UIStackView alloc] initWithArrangedSubviews:@[innerText, sized(10, 40)]];
    inner.axis = UILayoutConstraintAxisVertical;
    UIStackView *row = [[UIStackView alloc] initWithArrangedSubviews:@[big, sized(10, 10), small, inner]];
    row.alignment = UIStackViewAlignmentFirstBaseline;
    row.frame = CGRectMake(0, 0, 300, 100);
    [root addSubview:row];
    layout_tree(root);
    CGFloat bigBaseline = CGRectGetMaxY(big.frame) + big.font.descender;
    CGFloat smallBaseline = CGRectGetMaxY(small.frame) + small.font.descender;
    CGRect innerTextFrame = [innerText convertRect:innerText.bounds toView:row];
    CGFloat boxTop = [row.arrangedSubviews[1] frame].origin.y;
    CHECK(fabs(bigBaseline - smallBaseline) <= 1.5 && fabs(innerTextFrame.origin.y - big.frame.origin.y) <= 1.5 && fabs(boxTop - big.frame.origin.y) <= 1.5,
          NAMED(@"first-baseline alignment puts labels on one baseline and a view or a nested stack at the top of the text: %g %g, tops %g %g %g", bigBaseline, smallBaseline, big.frame.origin.y, boxTop, innerTextFrame.origin.y));
    CHECK(inner.viewForFirstBaselineLayout == innerText && row.viewForFirstBaselineLayout == big, "viewForFirstBaselineLayout of vertical and horizontal stacks");
    UILabel *top = label(@"top", 20), *bottom = label(@"bottom", 12);
    UIStackView *column = [[UIStackView alloc] initWithArrangedSubviews:@[top, bottom]];
    column.axis = UILayoutConstraintAxisVertical;
    column.baselineRelativeArrangement = YES;
    column.spacing = 30;
    column.frame = CGRectMake(0, 200, 200, 200);
    [root addSubview:column];
    layout_tree(root);
    CGFloat distance = (CGRectGetMaxY(bottom.frame) + bottom.font.descender) - (CGRectGetMaxY(top.frame) + top.font.descender);
    CHECK(fabs(distance - 30) <= 1.5, NAMED(@"baselineRelativeArrangement spaces baselines: %g", distance));
}

@interface LayoutTestDelegate : UIResponder <UIApplicationDelegate>
@property (nonatomic, strong) UIWindow *window;
@property (nonatomic, strong) UILabel *status;
@end

@implementation LayoutTestDelegate

- (BOOL)application:(UIApplication *)application didFinishLaunchingWithOptions:(NSDictionary *)options
{
    [[NSFileManager defaultManager] createDirectoryAtPath:results_folder withIntermediateDirectories:YES attributes:nil error:NULL];
    [[NSFileManager defaultManager] removeItemAtPath:[results_folder stringByAppendingPathComponent:@"layout.done"] error:NULL];
    charon_log_to([results_folder stringByAppendingPathComponent:@"layout.log"]);
    printf("layout device test started\n");
    UIViewController *host = [[UIViewController alloc] init];
    host.view.backgroundColor = [UIColor whiteColor];
    self.window = [[UIWindow alloc] initWithFrame:[UIScreen mainScreen].bounds];
    self.window.rootViewController = host;
    [self.window makeKeyAndVisible];
    after(1, ^{
        @autoreleasepool {
            test_mechanism();
            test_unknown_attributes();
            test_activation();
            test_margins();
            test_anchors();
            test_guides();
            test_stack_api();
            test_engine_multiplier();
            test_engine_fitting();
            test_stack_table();
        }
        [self runWindowTest:host];
    });
    return YES;
}

- (void)runWindowTest:(UIViewController *)host
{
    UIStackView *stack = [[UIStackView alloc] initWithArrangedSubviews:@[sized(40, 40), sized(50, 40), sized(60, 40)]];
    stack.spacing = 10;
    stack.translatesAutoresizingMaskIntoConstraints = NO;
    UILabel *status = label(@"Running", 17);
    status.translatesAutoresizingMaskIntoConstraints = NO;
    UIStackView *column = [[UIStackView alloc] initWithArrangedSubviews:@[status, stack]];
    column.axis = UILayoutConstraintAxisVertical;
    column.alignment = UIStackViewAlignmentCenter;
    column.spacing = 20;
    column.translatesAutoresizingMaskIntoConstraints = NO;
    [host.view addSubview:column];
    [NSLayoutConstraint activateConstraints:@[[column.centerXAnchor constraintEqualToAnchor:host.view.centerXAnchor], [column.centerYAnchor constraintEqualToAnchor:host.view.centerYAnchor]]];
    self.status = status;
    after(1, ^{
        CHECK(close_enough(stack.frame.size.width, 170) && close_enough(stack.frame.size.height, 40), NAMED(@"stack in a window lays out on the run loop: %@", NSStringFromCGRect(stack.frame)));
        [[stack.arrangedSubviews objectAtIndex:1] setHidden:YES];
        after(1, ^{
            CHECK(close_enough(stack.frame.size.width, 110) && close_enough([[stack.arrangedSubviews objectAtIndex:2] frame].origin.x, 50), NAMED(@"hiding an arranged view collapses it on the run loop: %@", NSStringFromCGRect(stack.frame)));
            [self finish];
        });
    });
}

- (void)finish
{
    printf("checks=%d failures=%d\n", charon_checks, charon_failures);
    self.status.text = [NSString stringWithFormat:@"%@ checks=%d failures=%d", charon_failures ? @"FAIL" : @"ok", charon_checks, charon_failures];
    after(1, ^{
        NSString *summary = [NSString stringWithFormat:@"%@ checks=%d failures=%d\n", charon_failures ? @"FAIL" : @"ok", charon_checks, charon_failures];
        [summary writeToFile:[results_folder stringByAppendingPathComponent:@"layout.done"] atomically:YES encoding:NSUTF8StringEncoding error:NULL];
    });
}

@end

int main(int argc, char **argv)
{
    @autoreleasepool {
        return UIApplicationMain(argc, argv, nil, NSStringFromClass([LayoutTestDelegate class]));
    }
