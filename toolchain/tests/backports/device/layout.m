static NSString *image_of(IMP implementation)
{
    Dl_info info;
    return implementation && dladdr((void *)implementation, &info) ? [@(info.dli_fname) lastPathComponent] : @"?";
}

static BOOL close_enough(CGFloat a, CGFloat b)
{
    return fabs(a - b) <= 1.01;
}

static BOOL rect_close(CGRect a, CGRect b)
{
    return close_enough(a.origin.x, b.origin.x) && close_enough(a.origin.y, b.origin.y) && close_enough(a.size.width, b.size.width) && close_enough(a.size.height, b.size.height);
}

static void mark(UIView *view)
{
    [view setNeedsLayout];
    for (UIView *subview in view.subviews)
        mark(subview);
}

static void layout_tree(UIView *root)
{
    mark(root);
    [root layoutIfNeeded];
}

