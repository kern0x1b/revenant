local function swiftui_weak_import_waiver(add_values)
    add_values("revenant.waive.weak-imports",
               "every weak import is reached only behind #available or carried by the backports: the runtime's overlays built with availability checking on, Combine's run-loop timer tolerance, compiler-rt's version check")
end

target("SwiftUIDemo")
    add_rules("@addon/revenant/app", "@addon/revenant/swift")
    add_deps("SwiftUI")
    add_files("Demo/*.swift")
    add_files("Demo/device/gesture.m")
    add_includedirs("Demo/device")
    add_packages("apple-backports")
    add_frameworks("UIKit", "Foundation", "CoreGraphics", "QuartzCore", "CoreData")
    set_values("swift.flags", "-import-objc-header", path.join(os.scriptdir(), "Demo", "device", "bridge.h"))
    set_optimize("fastest")
    set_values("app.plist-file", "Info.plist")
    set_values("app.plist", "CFBundleIdentifier=space.kern0x1b.swiftui.demo", "CFBundleDisplayName=SwiftUI")
    set_values("revenant.libraries", "apple-backports")
    set_values("revenant.control", "control")
    swiftui_weak_import_waiver(add_values)

