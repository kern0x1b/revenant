import("core.base.json")

local USAGE = [[usage: ./xmakew l -P . frameworks/ReactNative/tools/coverage.lua [--check] [--root DIR]
  writes docs/reference/react-native/coverage.md from frameworks/ReactNative/src/coverage.json, the one place that says what of React Native
  and of the Expo SDK runs on iOS 6.1.3. With --check it writes nothing and fails when the document is not what the data makes.
  Every run also checks the data against frameworks/ReactNative/src/stubs.json, the stubs the build stands in with, and the sources:
  a row verified on the phone or built cannot rest on a stub, a row that a local copy of its file replaces cannot be real, and
  every stub class in the sources is listed in stubs.json. --root checks another checkout (the tests use it on fixtures).]]

local STATUSES = {
    {"real", "built from the module's own sources, with no stub and no substitute"},
    {"partial", "built and running, with a named part left out or rewritten"},
    {"js", "no native code of its own, so it runs with the bundle"},
    {"stub", "a name-only module or a plain-view replacement: the application loads and the feature is absent"},
    {"missing", "native code that is not built yet"},
    {"evaluate", "not attempted; the note says what iOS 6 offers"},
    {"impossible", "the system service does not exist before the iOS release the note names"},
    {"n/a", "build, web or Android only: nothing to run on the phone"}
}

local VERIFIED = {
    phone = "seen working on the phone",
    build = "compiles and links; not exercised",
    none = "not checked"
}

local GROUPS = {
    {"core", "React Native core"},
    {"sdk", "Expo SDK packages and the native libraries the SDK pins"},
    {"community", "Other native libraries applications use"}
}

local STUB_FIELDS = {"name", "file", "module", "owner", "reason"}

local DECLARED = {
    ["src/expo/StubModules.swift"] = function (text)
        local names = {}
        for name in text:gmatch("public final class (Stub%w+): Module") do
            names[name] = true
        end
        return names
    end
}

local function cell(text)
    return (tostring(text or ""):gsub("|", "\\|"))
end

local function source(root, rel)
    return io.readfile(path.join(root, "frameworks", "ReactNative", rel))
end

local function local_copies(text)
    local block = text:match("local LOCAL_COPIES = (%b{})") or ""
    local packages = {}
    for package in block:gmatch('%["([^"]+)"%]') do
        table.insert(packages, package)
    end
    return packages
end

function render(data, registry)
    local lines = {
        "# What runs: React Native and the Expo SDK on iOS 6.1.3",
        "",
        string.format("React Native %s, Expo SDK %s, measured on an %s. Generated by `frameworks/ReactNative/tools/coverage.lua` from `frameworks/ReactNative/src/coverage.json` and `frameworks/ReactNative/src/stubs.json`; change the data, not this file.",
                      data.reactNative, data.sdk, data.device),
        "",
        "## Status",
        "",
        "| Status | Meaning | Count |",
        "| --- | --- | --- |"
    }
    local counts = {}
    for _, row in ipairs(data.rows) do
        counts[row.status] = (counts[row.status] or 0) + 1
    end
    for _, status in ipairs(STATUSES) do
        table.insert(lines, string.format("| %s | %s | %d |", status[1], status[2], counts[status[1]] or 0))
    end
    table.insert(lines, string.format("| total | | %d |", #data.rows))
    table.insert(lines, "")
    table.insert(lines, "Checked: " .. table.concat({"phone: " .. VERIFIED.phone, "build: " .. VERIFIED.build, "none: " .. VERIFIED.none}, "; ") .. ".")
    for _, group in ipairs(GROUPS) do
        table.insert(lines, "")
        table.insert(lines, "## " .. group[2])
        table.insert(lines, "")
        table.insert(lines, "| Module | Version | Native | Status | Checked | Note |")
        table.insert(lines, "| --- | --- | --- | --- | --- | --- |")
        for _, row in ipairs(data.rows) do
            if row.group == group[1] then
                table.insert(lines, string.format("| %s | %s | %s | %s | %s | %s |", cell(row.id), cell(row.version),
                                                  row.native and "yes" or "no", row.status, row.verified, cell(row.note)))
            end
        end
    end
    table.insert(lines, "")
    table.insert(lines, "## Stubs")
    table.insert(lines, "")
    table.insert(lines, "What the build stands in with for a module it does not build. Each is listed in `frameworks/ReactNative/src/stubs.json`, which the build reads; its owner is the row above that it stands in for. A stub is removed when its owner is built as a real module.")
    table.insert(lines, "")
    table.insert(lines, "| Stub | Module | File | Owner | Reason |")
    table.insert(lines, "| --- | --- | --- | --- | --- |")
    for _, stub in ipairs(registry.stubs) do
        table.insert(lines, string.format("| %s | %s | %s | %s | %s |", cell(stub.name), cell(stub.module), cell(stub.file), cell(stub.owner), cell(stub.reason)))
    end
    table.insert(lines, "")
    return table.concat(lines, "\n")
end

local function data_problems(data)
    local known = {}
    for _, status in ipairs(STATUSES) do
        known[status[1]] = true
    end
    local seen = {}
    local problems = {}
    for _, row in ipairs(data.rows) do
        if not known[row.status] then
            table.insert(problems, row.id .. ": unknown status " .. tostring(row.status))
        end
        if not VERIFIED[row.verified] then
            table.insert(problems, row.id .. ": unknown check " .. tostring(row.verified))
        end
        if seen[row.group .. "/" .. row.id] then
            table.insert(problems, row.id .. ": listed twice in " .. row.group)
        end
        seen[row.group .. "/" .. row.id] = true
        if (row.status == "stub" or row.status == "partial" or row.status == "impossible" or row.status == "evaluate") and (row.note or "") == "" then
            table.insert(problems, row.id .. ": a " .. row.status .. " row needs its reason in the note")
        end
    end
    return problems
end

local function stub_problems(data, registry, root)
    local problems = {}
    local rows, owned, names, texts = {}, {}, {}, {}
    for _, row in ipairs(data.rows) do
        rows[row.id] = row
    end
    for _, stub in ipairs(registry.stubs) do
        for _, field in ipairs(STUB_FIELDS) do
            if (stub[field] or "") == "" then
                table.insert(problems, "stubs.json: " .. tostring(stub.name) .. " has no " .. field)
            end
        end
        if names[stub.name] then
            table.insert(problems, "stubs.json: " .. stub.name .. " is listed twice")
        end
        names[stub.name] = true
        if not rows[stub.owner] then
            table.insert(problems, "stubs.json: " .. stub.name .. " stands in for " .. tostring(stub.owner) .. ", which has no coverage row")
        end
        owned[stub.owner] = owned[stub.owner] or {}
        table.insert(owned[stub.owner], stub.name)
        if not texts[stub.file] then
            texts[stub.file] = source(root, stub.file)
        end
        if not texts[stub.file]:find(stub.name, 1, true) then
            table.insert(problems, "stubs.json: " .. stub.name .. " is not in " .. stub.file)
        end
    end
    for file, text in pairs(texts) do
        local rule = DECLARED[file]
        if not rule then
            table.insert(problems, file .. ": no rule says which stubs it declares")
        else
            local declared, listed = rule(text), {}
            for _, stub in ipairs(registry.stubs) do
                if stub.file == file then
                    listed[stub.name] = true
                end
            end
            for name in pairs(declared) do
                if not listed[name] then
                    table.insert(problems, file .. " declares " .. name .. ", which stubs.json does not list")
                end
            end
            for name in pairs(listed) do
                if not declared[name] then
                    table.insert(problems, "stubs.json lists " .. name .. ", which " .. file .. " does not declare")
                end
            end
        end
    end
    for _, row in ipairs(data.rows) do
        local stubs = owned[row.id]
        if row.status == "stub" and not stubs then
            table.insert(problems, row.id .. ": status stub, but no entry of stubs.json stands in for it")
        end
        if stubs and row.verified ~= "none" then
            table.insert(problems, row.id .. ": verified " .. row.verified .. " against stub " .. table.concat(stubs, ", ") .. "; a stub is not a check of the module")
        end
        if stubs and row.status == "real" then
            table.insert(problems, row.id .. ": status real, but stub " .. table.concat(stubs, ", ") .. " stands in for it")
        end
        if row.native and row.verified ~= "none" and row.status ~= "real" and row.status ~= "partial" and row.status ~= "js" then
            table.insert(problems, row.id .. ": verified " .. row.verified .. " but status " .. row.status .. " is not a built module")
        end
    end
    local expo = source(root, "src/expo/xmake.lua")
    for _, package in ipairs(local_copies(expo)) do
        local row = rows[package]
        if not row then
            table.insert(problems, "src/expo/xmake.lua: LOCAL_COPIES names " .. package .. ", which has no coverage row")
        elseif row.status == "real" then
            table.insert(problems, package .. ": status real, but src/expo/xmake.lua replaces its file with a local copy (LOCAL_COPIES)")
        end
    end
    return problems
end

function validate(data, registry, root)
    local problems = data_problems(data)
    for _, problem in ipairs(stub_problems(data, registry, root)) do
        table.insert(problems, problem)
    end
    return problems
end

function main(...)
    local shared = import("@addon.revenant.member", {anonymous = true})
    local given = shared.arguments({...}, {check = "switch", help = "switch", root = "value"})
    if given.help then
        print(USAGE)
        return
    end
    local root = given.root and path.absolute(given.root) or path.join(os.scriptdir(), "..", "..", "..")
    local src = path.join(root, "frameworks", "ReactNative", "src")
    local data = json.decode(io.readfile(path.join(src, "coverage.json")))
    local registry = json.decode(io.readfile(path.join(src, "stubs.json")))
    local problems = validate(data, registry, root)
    if #problems > 0 then
        raise("coverage.json and stubs.json:\n  %s", table.concat(problems, "\n  "))
    end
    local target = path.join(root, "docs", "reference", "react-native", "coverage.md")
    local text = render(data, registry)
    if given.check then
        if io.readfile(target) ~= text then
            raise("%s is not what coverage.json and stubs.json make; run this tool without --check", target)
        end
        print("coverage.md matches coverage.json and stubs.json")
        return
    end
    io.writefile(target, text)
    print("wrote " .. target)
end
