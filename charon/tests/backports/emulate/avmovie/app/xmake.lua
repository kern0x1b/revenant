set_project("charonavmovieprobe")
set_version("0.0.1")
-- The AVMovie probe of tests/backports/host/avf-movie4, as an application launched through SpringBoard (xmake emulate launch).
-- The movies are the application's resources: run-app.sh copies the host's movies into movies/ beside this file.
local root = os.getenv("CHARAVMOVIE_ROOT") or path.join(os.scriptdir(), "../../../../..")
add_repositories("charon " .. root)
add_addons("charon v0.8.17")
set_config("apple_minimum", os.getenv("CHARAVMOVIE_MINIMUM") or "6.1.3")
add_requires("charon@apple-backports", {alias = "apple-backports", configs = {avfoundation = true}})
includes("@addon/charon/apple-ios")
includes("@addon/charon/emulate")
set_defaultplat("iphoneos")
set_defaultarchs("iphoneos|armv7")

target("charonavmovieprobe")
    add_rules("@addon/charon/app")
    add_files(path.join(root, "tests/backports/emulate/avmovie/app/main.m"))
    add_files(path.join(root, "tests/backports/host/avf-movie4/probe.m"))
    add_defines("CHARON_AVMOVIE_APP=1")
    add_mflags("-fobjc-arc")
    add_ldflags("-fobjc-arc", {force = true})
    add_frameworks("Foundation", "UIKit", "AVFoundation", "CoreMedia")
    add_packages("apple-backports")
    set_values("charon.libraries", "apple-backports")
    set_values("app.plist-file", "Info.plist")
    set_values("app.resources", "movies")
    set_values("charon.control", "control")
