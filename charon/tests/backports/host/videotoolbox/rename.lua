local lib = import("vtlib", {rootdir = os.scriptdir(), anonymous = true})

function main(out, namesPath)
    if not out or not namesPath then
        raise("rename.lua: pass OUT NAMES")
    end
    local names = {}
    for _, line in ipairs(lib.file_lines(lib.read_text(namesPath))) do
        local name = lib.strip(line)
        if name ~= "" then
            names[#names + 1] = name
        end
    end
    local text = {"// Generated by rename.py: the port's constants, under names of their own.\n"}
    for _, name in ipairs(names) do
        text[#text + 1] = "#define " .. name .. " Charon" .. name .. "\n"
    end
    lib.write_text(out, table.concat(text))
end
