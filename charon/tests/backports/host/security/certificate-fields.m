bool CharonCertificateNameTLV(const uint8_t *bytes, size_t length, bool wantSubject,
                             size_t *outStart, size_t *outEnd);

typedef OSStatus (*CopyCommonName)(SecCertificateRef, CFStringRef *);
typedef OSStatus (*CopyEmails)(SecCertificateRef, CFArrayRef *);

int main(void)
{
    // UNBUFFERED, so output SURVIVES A CRASH. A mutant that segfaults mid-case would otherwise lose
    // every row printed before it, and the comparator would then say those rows "did not measure" and
    // name a truncated buffer instead of the crash.
    setvbuf(stdout, NULL, _IONBF, 0);
    @autoreleasepool {
        // the host's own accessors, off the SYSTEM handle, because this file defines the same names
        void *system = dlopen("/System/Library/Frameworks/Security.framework/Security", RTLD_LAZY | RTLD_LOCAL);
        CopyCommonName hostCN = (CopyCommonName)dlsym(system, "SecCertificateCopyCommonName");
        CopyEmails hostMail = (CopyEmails)dlsym(system, "SecCertificateCopyEmailAddresses");
        printf("host-symbols\t%s\n", (hostCN && hostMail) ? "both" : "MISSING");
        if (!hostCN || !hostMail)
            return 1;
        SecCertificateRef cert = SecCertificateCreateWithData(NULL,
                                    CFDataCreate(kCFAllocatorDefault, CharonCertificateFixtureDER,
                                                 (CFIndex)CharonCertificateFixtureLength));
        if (!cert) { printf("no-certificate\n"); return 1; }

        CFStringRef portName = NULL, hostName = NULL;
        OSStatus portStatus = SecCertificateCopyCommonName(cert, &portName);
        OSStatus hostStatus = hostCN(cert, &hostName);
        printf("common-name-status\t%ld\t%ld\n", (long)portStatus, (long)hostStatus);
        printf("common-name\t%s\t%s\n", portName ? [(__bridge NSString *)portName UTF8String] : "NULL",
                                    hostName ? [(__bridge NSString *)hostName UTF8String] : "NULL");
        if (!portName || !hostName || !CFEqual(portName, hostName))
            printf("WRONG\tcommon-name: port [%s] host [%s]\n",
                   portName ? [(__bridge NSString *)portName UTF8String] : "NULL",
                   hostName ? [(__bridge NSString *)hostName UTF8String] : "NULL");

        CFArrayRef portMail = NULL, hostMailOut = NULL;
        portStatus = SecCertificateCopyEmailAddresses(cert, &portMail);
        hostStatus = hostMail(cert, &hostMailOut);
        printf("email-status\t%ld\t%ld\n", (long)portStatus, (long)hostStatus);
        for (int i = 0; i < (int)(portMail ? CFArrayGetCount(portMail) : 0); i++)
            printf("email-port-%d\t%s\n", i, [(__bridge NSString *)CFArrayGetValueAtIndex(portMail, i) UTF8String]);
        for (int i = 0; i < (int)(hostMailOut ? CFArrayGetCount(hostMailOut) : 0); i++)
            printf("email-host-%d\t%s\n", i, [(__bridge NSString *)CFArrayGetValueAtIndex(hostMailOut, i) UTF8String]);
        printf("email-count\t%lu\t%lu\n", (unsigned long)(portMail ? CFArrayGetCount(portMail) : 0),
               (unsigned long)(hostMailOut ? CFArrayGetCount(hostMailOut) : 0));

        // a NULL out-parameter and a NULL certificate are both refused, not crashed on
        printf("null-out\t%ld\n", (long)SecCertificateCopyCommonName(cert, NULL));
        printf("null-cert\t%ld\n", (long)SecCertificateCopyCommonName(NULL, &portName));
    }
    return 0;
}
