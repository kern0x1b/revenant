-- gen_cases.lua [SDK] - writes cases.m, the table the VideoToolbox class differential holds the port to,
-- from the SDK's own headers. A port of gen-cases.py, which says what the table is and why it is generated.
-- Run it as
--
--     xmake l gen_cases.lua "$VT_SDK" > cases.m
--
-- The SDK is the first argument, or VT_SDK when no argument is given (gen-cases.py read VT_SDK only; run.sh
-- passes the SDK). The bytes printed are the bytes gen-cases.py printed: the committed cases.m is what this
-- program writes, and cmp against it is the check. The text inside says "gen-cases.py" and "rename.py" on
-- purpose, because that is what the committed file says.

local G = import("gen_body", {rootdir = os.scriptdir()})
local V = import("vtlib", {rootdir = os.scriptdir()})

-- The first element of the Python's out list: the header of cases.m, up to the first row.
local H1 = [==[
#import <Foundation/Foundation.h>
#import "vtclass-cases.h"
#import <objc/runtime.h>

// GENERATED by gen-cases.py from the iOS 26.2 SDK's own VideoToolbox headers. Do not hand-edit: the
// table below is the SDK's shape, and a copy of it written by hand is a comparison that cannot fail.
//
// VTCLASS_NAME is how one source asks for a class in either build. In the host build it is the class's
// own name; in the port's build rename.py has #defined that name to Charon<class>, so the same line
// finds the port's class instead - one binary, two implementations, no second translation unit.
#define VTCLASS_STR_(x) #x
#define VTCLASS_STR(x) VTCLASS_STR_(x)
// No #ifdef here on purpose: rename.py #defines each class name to Charon<class> and force-includes
// that into the PORT's build, so stringifying the name through this macro yields the host's class in
// the host build and the port's renamed class in the port's - from one line, with no second lookup.
#define VTCLASS_NAME(x) VTCLASS_STR(x)

typedef struct {
    const char *name;
    const char *protocol;
    const char *classProperties;   // space separated accessors the SDK declares on the CLASS
    const char *instanceProperties; // space separated accessors the SDK declares on the INSTANCE
} VTClassShape;

static const VTClassShape vtClassShapes[] = {
// The class properties, then the instance ones, in the order the SDK declares them.]==]

-- The row for each class: {"name", "protocol", "class accessors", "instance accessors"}, the Python's
-- out.append('    {"%s", "%s", "%s", "%s"},' % ...). The accessors are the getter (or the name), the class ones
-- and the instance ones, in the order own then inherited, where inherited is each protocol's properties in
-- its own order and a name that is already there keeps its first entry (Python's inh.setdefault).
local function class_row(protocols, classes, c)
    local v = classes[c]
    local inh = G.odict_new()
    for _, pr in ipairs(v.protocols) do
        local pm = protocols[pr]
        if pm == nil then
            V.fail("gen_cases.lua: KeyError: " .. V.py_repr(pr))
        end
        for _, n in ipairs(pm.keys) do
            G.odict_setdefault(inh, n, pm.map[n])
        end
    end
    -- list(own.items()) + list(inh.items())
    local entries = {}
    for _, k in ipairs(v.own.keys) do
        entries[#entries + 1] = {k, v.own.map[k]}
    end
    for _, k in ipairs(inh.keys) do
        entries[#entries + 1] = {k, inh.map[k]}
    end
    local cp, ip = {}, {}
    for _, entry in ipairs(entries) do
        local n, p = entry[1], entry[2]
        -- Python: p["getter"] or n, where "" is false
        local name = n
        if p.getter ~= nil and p.getter ~= "" then
            name = p.getter
        end
        if p["class"] then
            cp[#cp + 1] = name
        else
            ip[#ip + 1] = name
        end
    end
    local proto = v.protocols[1] or ""
    return string.format('    {"%s", "%s", "%s", "%s"},', c, proto, table.concat(cp, " "), table.concat(ip, " "))
end


-- The rest of the Python's out list, after the rows: the lookup table's end, and the code the host and the
-- port both run. It is one string, and it begins with a newline, as the Python's '''...''' did.
local H3 = "\n" .. [==[
static NSArray *VTCLASSShapes(void)
{
    static NSArray *shapes;
    if (!shapes) {
        NSMutableArray *collected = [NSMutableArray array];
        for (unsigned i = 0; i < sizeof(vtClassShapes) / sizeof(vtClassShapes[0]); i++) {
            [collected addObject:@{
                @"name": @(vtClassShapes[i].name),
                @"protocol": @(vtClassShapes[i].protocol),
                @"classProperties": @(vtClassShapes[i].classProperties),
                @"instanceProperties": @(vtClassShapes[i].instanceProperties),
            }];
        }
        shapes = collected;
    }
    return shapes;
}

static NSArray *Words(NSString *text)
{
    if (!text.length)
        return @[];
    NSMutableArray *words = [NSMutableArray array];
    for (NSString *word in [text componentsSeparatedByString:@" "])
        if (word.length)
            [words addObject:word];
    return words;
}

void vtclass_run(CertificateRecorder record)
{
    NSString *covered = [NSString stringWithContentsOfFile:@(getenv("VTCLASS_COVERED")) encoding:NSUTF8StringEncoding error:NULL] ?: @"";
    NSMutableSet *enabled = [NSMutableSet set];
    for (NSString *line in [covered componentsSeparatedByString:@"\n"]) {
        NSString *name = [line stringByTrimmingCharactersInSet:[NSCharacterSet whitespaceCharacterSet]];
        if (name.length)
            [enabled addObject:name];
    }

    for (NSDictionary *shape in VTCLASSShapes()) {
        NSString *declared = shape[@"name"];
        // VTCLASS_COVERED holds the SDK's own spelling; the port's class is the renamed one, so the
        // lookup below goes through the macro and the two builds ask for their own class by one line.
        if (![enabled containsObject:declared])
            continue;
        NSString *lookup = nil;
        if ([declared isEqualToString:@"VTFrameProcessor"])                  lookup = @VTCLASS_NAME(VTFrameProcessor);
        else if ([declared isEqualToString:@"VTFrameProcessorFrame"])         lookup = @VTCLASS_NAME(VTFrameProcessorFrame);
        else if ([declared isEqualToString:@"VTFrameProcessorOpticalFlow"])   lookup = @VTCLASS_NAME(VTFrameProcessorOpticalFlow);
        else if ([declared isEqualToString:@"VTFrameRateConversionConfiguration"]) lookup = @VTCLASS_NAME(VTFrameRateConversionConfiguration);
        else if ([declared isEqualToString:@"VTFrameRateConversionParameters"])   lookup = @VTCLASS_NAME(VTFrameRateConversionParameters);
        else if ([declared isEqualToString:@"VTLowLatencyFrameInterpolationConfiguration"]) lookup = @VTCLASS_NAME(VTLowLatencyFrameInterpolationConfiguration);
        else if ([declared isEqualToString:@"VTLowLatencyFrameInterpolationParameters"])   lookup = @VTCLASS_NAME(VTLowLatencyFrameInterpolationParameters);
        else if ([declared isEqualToString:@"VTLowLatencySuperResolutionScalerConfiguration"]) lookup = @VTCLASS_NAME(VTLowLatencySuperResolutionScalerConfiguration);
        else if ([declared isEqualToString:@"VTLowLatencySuperResolutionScalerParameters"])   lookup = @VTCLASS_NAME(VTLowLatencySuperResolutionScalerParameters);
        else if ([declared isEqualToString:@"VTMotionBlurConfiguration"])   lookup = @VTCLASS_NAME(VTMotionBlurConfiguration);
        else if ([declared isEqualToString:@"VTMotionBlurParameters"])      lookup = @VTCLASS_NAME(VTMotionBlurParameters);
        else if ([declared isEqualToString:@"VTOpticalFlowConfiguration"])  lookup = @VTCLASS_NAME(VTOpticalFlowConfiguration);
        else if ([declared isEqualToString:@"VTOpticalFlowParameters"])     lookup = @VTCLASS_NAME(VTOpticalFlowParameters);
        else if ([declared isEqualToString:@"VTSuperResolutionScalerConfiguration"]) lookup = @VTCLASS_NAME(VTSuperResolutionScalerConfiguration);
        else if ([declared isEqualToString:@"VTSuperResolutionScalerParameters"])   lookup = @VTCLASS_NAME(VTSuperResolutionScalerParameters);
        else if ([declared isEqualToString:@"VTTemporalNoiseFilterConfiguration"]) lookup = @VTCLASS_NAME(VTTemporalNoiseFilterConfiguration);
        else if ([declared isEqualToString:@"VTTemporalNoiseFilterParameters"])   lookup = @VTCLASS_NAME(VTTemporalNoiseFilterParameters);
        if (!lookup) {
            record([@"class.unknown" stringByAppendingString:declared], @"1");
            continue;
        }
        Class cls = NSClassFromString(lookup);
        record([@"class." stringByAppendingString:declared], cls ? @"1" : @"0");
        if (!cls)
            continue;
        NSString *proto = shape[@"protocol"];
        if (proto.length)
            record([@"conforms." stringByAppendingString:declared], [cls conformsToProtocol:NSProtocolFromString(proto)] ? @"1" : @"0");
        for (NSString *accessor in [Words(shape[@"classProperties"]) arrayByAddingObjectsFromArray:Words(shape[@"instanceProperties"])]) {
            SEL selector = NSSelectorFromString(accessor);
            NSString *tag = [NSString stringWithFormat:@"%@.%@", declared, accessor];
            record([@"selector." stringByAppendingString:tag], NSStringFromSelector(selector));
            // WHERE the accessor lives, not what it is called: a class property asked for by its
            // spelling is invisible to a comparison that only reads the spelling, which is why the
            // first mutation of this family - a class property becoming an instance method - survived
            // until the question was asked this way.
            record([@"isClass." stringByAppendingString:tag], class_getClassMethod(cls, selector) ? @"1" : @"0");
            record([@"isInstance." stringByAppendingString:tag], [cls instancesRespondToSelector:selector] ? @"1" : @"0");
        }
    }
    // The shape above is the SDK's, and the host answers it. The round-trip below is the port's own
    // values, and it lives in its own hand-written file because it CALLS the initialiser rather than
    // describing it - there is nothing in the SDK's headers to generate it from.
    vtclass_roundtrip(record);
}]==]

function main(...)
    local argv = {...}
    local sdk = argv[1]
    if sdk == nil or sdk == "" then
        sdk = os.getenv("VT_SDK") or ""
    end
    if sdk == "" then
        V.fail("gen_cases.lua: set VT_SDK to an iPhoneOS*.sdk, or pass it as the first argument")
    end
    local header = V.join_path(sdk, "System/Library/Frameworks/VideoToolbox.framework/Headers")

    local out = {H1}
    local rows_ok, protocols, classes = nil, nil, nil
    try {
        function()
            protocols, classes = G.parse(V.header_text(header))
        end,
        catch {
            function(err)
                V.fail(tostring(err))
            end
        }
    }
    for _, c in ipairs(G.ORDER()) do
        out[#out + 1] = class_row(protocols, classes, c)
    end
    out[#out + 1] = "};"
    out[#out + 1] = ""
    out[#out + 1] = H3
    print(table.concat(out, "\n"))
end
