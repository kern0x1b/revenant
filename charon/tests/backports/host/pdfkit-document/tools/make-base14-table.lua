-- make-base14-table.lua - generate the standard fourteen's advances, FROM A MEASUREMENT, into a C table.
--
--     xmake l tools/make-base14-table.lua [<host-base14 output>] <out.c> [--check]
--
-- With no measurement argument it reads `base14-measurement.txt` beside this file, which is the run output committed next
-- to it - so `--check` runs from a clean checkout, which is the only way a check is a check.
--
-- The table in the port is the standard metrics of PDF 1.7 Annex F, and it is generated from a run of `tools/host-base14.m`
-- over `tools/make-font-fixtures.lua`'s base-fourteen fixtures rather than typed by hand, for the reason the numbers are
-- not in any API: CGFontCreateWithFontName answers 43.2070 for "page 1" in Courier where the host answers 43.2000, so the
-- only source that answers the host is a measurement of the host. Running this tool again against the same run output must
-- reproduce the file byte for byte, and `--check` says so rather than rewriting it.
--
-- WHAT IS MEASURED: every printable ASCII code, 32..126, one fixture per face per half so that no code is lost to the host's
-- own cut at 83 characters in one show operator, and a third fixture per face whose whole-line rect gives code 32 - the
-- space is a leading character in the first half and the line rule trims that, so its width is derived as whole - 2 * w(A)
-- over two numbers already measured.
--
-- The unit is THOUSANDTHS OF AN EM, which is what /Widths itself is written in (PDF 1.7 Table 8.27), so a width enters the
-- geometry as value * size / 1000 with no conversion anywhere else.
--
-- The Python regular expressions are matched by hand below, each one named beside the code that matches it.

-- The fourteen, in the spelling the /BaseFont name uses (PDF 1.7 Table 7.21). The key is the file stem
-- make-font-fixtures writes for each, which is the face name lowercased.
local FACES = {
    "Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
    "Courier", "Courier-Bold", "Courier-Oblique", "Courier-BoldOblique",
    "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic",
    "Symbol", "ZapfDingbats",
}

local FIRST_CODE = 32
local LAST_CODE = 126

-- The two markers that say which part of the .m is generated: the header line the generator writes, and the first line of
-- the hand-written footer below the table. `--check` compares what is BETWEEN them.
local GENERATED_MARKER = "// GENERATED by tools/make-base14-table.py"
local FOOTER_MARKER = "// The width of `code`"

local PREFIX = "cgfixture-base14-"

local function file_exists(file)
    local handle = io.open(file, "rb")
    if handle then
        handle:close()
        return true
    end
    return false
end

-- Python's open(path).read() in text mode: "\r\n" and "\r" become "\n".
local function read_text(file)
    local handle = assert(io.open(file, "rb"))
    local text = handle:read("a")
    handle:close()
    text = text:gsub("\r\n", "\n")
    text = text:gsub("\r", "\n")
    return text
end

-- The lines of a text, without their line ends, as Python's `for line in file` gives them with the ends taken off.
local function lines_of(text)
    local lines = {}
    local start = 1
    while start <= #text do
        local stop = text:find("\n", start, true)
        if not stop then
            lines[#lines + 1] = text:sub(start)
            break
        end
        lines[#lines + 1] = text:sub(start, stop - 1)
        start = stop + 1
    end
    return lines
end

-- Python's round(x) for a float: the nearest integer, a tie going to the even one.
local function round_half_even(x)
    local floor = math.floor(x)
    local diff = x - floor
    if diff > 0.5 then
        return floor + 1
    elseif diff < 0.5 then
        return floor
    elseif floor % 2 == 0 then
        return floor
    end
    return floor + 1
end

-- Python's float() of a matched run; a run float() refuses is the ValueError Python raises, here as a raise.
local function number(text)
    local value = tonumber(text)
    if value == nil then
        raise("ValueError: could not convert string to float: " .. text)
    end
    return value
end

-- The longest run of characters from `allowed` (a Lua character class) that starts at `at`: the run, and the position
-- after it. nil when there is no such run at `at` (a regex's `+` needs one or more).
local function run_at(text, at, allowed)
    local stop = at
    while stop <= #text and text:sub(stop, stop):find(allowed) do
        stop = stop + 1
    end
    if stop == at then
        return nil
    end
    return text:sub(at, stop - 1), stop
end

local DOTS_DASHES_DIGITS = "[%d%.%-]"   -- [\d.-]
local DOTS_DIGITS = "[%d%.]"           -- [\d.]
local DIGITS = "%d"                    -- \d

-- The literal `word` at `at`: the position after it, or nil.
local function literal_at(text, at, word)
    if text:sub(at, at + #word - 1) == word then
        return at + #word
    end
    return nil
end

-- The position of the LAST place `word` starts in `text` at or after `from` - the greedy `(.+)` in front of it takes the
-- longest group, so the last occurrence is the one the regex's group ends on.
local function last_occurrence(text, word, from)
    local found = nil
    local search = from
    while true do
        local s = text:find(word, search, true)
        if not s then
            return found
        end
        found = s
        search = s + 1
    end
end

-- The face named in a line that starts `cgfixture-base14-(.+)<suffix>`, with the suffix found at its LAST place and the
-- group at least one character. Returns the face and the position just after the suffix, or nil.
local function face_before(line, suffix)
    if line:sub(1, #PREFIX) ~= PREFIX then
        return nil
    end
    local at = last_occurrence(line, suffix, #PREFIX + 2)
    if not at then
        return nil
    end
    return line:sub(#PREFIX + 1, at - 1), at + #suffix
end

-- read(path): {face: {code: width in thousandths of an em}} out of a host-base14 run.
--   A line with " text-len=" is a fixture's header: re.match(r"cgfixture-base14-(.+)-\d\.pdf", line) names the face, and
--   a line that does not match it is skipped WITHOUT resetting the face. Any other line is read as a glyph:
--   re.match(r"\s*(\d+) (.|\S) x=([\d.]+) w=([\d.]+)", line), when a face is set.
local function read(path)
    local widths, face = {}, nil
    for _, line in ipairs(lines_of(read_text(path))) do
        if line:find(" text-len=", 1, true) then
            -- cgfixture-base14-(.+)-\d\.pdf: the group ends where the last "-<digit>.pdf" begins.
            local last, search = nil, #PREFIX + 2
            while true do
                local s = line:find("-%d%.pdf", search)
                if not s then
                    break
                end
                last = s
                search = s + 1
            end
            if line:sub(1, #PREFIX) == PREFIX and last and last >= #PREFIX + 2 then
                face = line:sub(#PREFIX + 1, last - 1)
                widths[face] = widths[face] or {}
            end
        elseif face ~= nil then
            -- \s*(\d+) (.|\S) x=([\d.]+) w=([\d.]+)
            local at = line:find("%S") or (#line + 1)
            local code, after_code = run_at(line, at, DIGITS)
            if code and line:sub(after_code, after_code) == " " then
                -- (.|\S): any one character but a line end, and the literal " x=" follows it
                local char_at = after_code + 1
                if char_at <= #line then
                    local after_x = literal_at(line, char_at + 1, " x=")
                    if after_x then
                        local _, after_x_run = run_at(line, after_x, DOTS_DIGITS)
                        if after_x_run and literal_at(line, after_x_run, " w=") then
                            local w = run_at(line, after_x_run + 3, DOTS_DIGITS)
                            if w then
                                widths[face][tonumber(code)] = number(w) / 12.0 * 1000.0
                            end
                        end
                    end
                end
            end
        end
    end
    return widths
end

-- The position after `text` at `at` when the regex's `[\d.-]+,` shape is there: the run, the comma's next position.
local function value_then_comma(line, at)
    local value, after = run_at(line, at, DOTS_DASHES_DIGITS)
    if value and line:sub(after, after) == "," then
        return value, after + 1
    end
    return nil
end

-- read_spaces(path): {face: width of code 32}, from the -space fixtures' whole-line rects and the w(A) beside them.
--   cgfixture-base14-(.+)-space\.pdf text-len=(\d+) whole=([\d.-]+),[\d.-]+,([\d.-]+),[\d.-]+   (the third value is kept)
--   \s*65 A x=([\d.-]+) w=([\d.-]+)
local function read_spaces(path)
    local spaces, face, pending = {}, nil, nil
    for _, line in ipairs(lines_of(read_text(path))) do
        local matched = false
        local name, after_name = face_before(line, "-space.pdf text-len=")
        if name then
            local _, after_len = run_at(line, after_name, DIGITS)
            local whole_at = after_len and literal_at(line, after_len, " whole=")
            if whole_at then
                local _, after_x0 = value_then_comma(line, whole_at)
                local _, after_y0 = value_then_comma(line, after_x0 or #line + 2)
                if after_y0 then
                    local x1, after_x1 = value_then_comma(line, after_y0)
                    if x1 and run_at(line, after_x1, DOTS_DASHES_DIGITS) then
                        face = name
                        pending = number(x1)
                        matched = true
                    end
                end
            end
        end
        if not matched then
            local at = line:find("%S") or (#line + 1)
            local after_head = literal_at(line, at, "65 A x=")
            if after_head then
                local _, after_x = run_at(line, after_head, DOTS_DASHES_DIGITS)
                local w_at = after_x and literal_at(line, after_x, " w=")
                local w = w_at and run_at(line, w_at, DOTS_DASHES_DIGITS)
                if w and face ~= nil and pending ~= nil then
                    spaces[face] = (pending - 2.0 * number(w)) / 12.0 * 1000.0
                    pending = nil
                end
            end
        end
    end
    return spaces
end

-- read_descents(path): {face: descent in thousandths of an em}, from the -descent fixtures.
--   cgfixture-base14-(.+)-descent\.pdf text-len=\d+ whole=[\d.-]+,([\d.-]+),
-- The fixture draws "Ag" at y=720 with no /FontDescriptor, so the descent is (y - 720) * 1000 / 12, NEGATIVE; rounded to
-- four places as Python's round(x, 4) does.
local function read_descents(path, drawn_at, size)
    local descents = {}
    for _, line in ipairs(lines_of(read_text(path))) do
        local name, after_name = face_before(line, "-descent.pdf text-len=")
        if name then
            local _, after_len = run_at(line, after_name, DIGITS)
            local whole_at = after_len and literal_at(line, after_len, " whole=")
            if whole_at then
                local _, after_x0 = value_then_comma(line, whole_at)
                local y0 = after_x0 and value_then_comma(line, after_x0)
                if y0 then
                    local value = number(y0)
                    descents[name] = tonumber(string.format("%.4f", (value - drawn_at) * 1000.0 / size))
                end
            end
        end
    end
    return descents
end

-- emit(widths, spaces, descents): the generated section of the .c file, as one string ending in a newline.
local function emit(widths, spaces, descents)
    local out = {}
    local function add(line)
        out[#out + 1] = line
    end
    add("// GENERATED by tools/make-base14-table.py from a run of tools/host-base14.m - do not edit.")
    add("//")
    add("// The standard fourteen's advances, in THOUSANDTHS OF AN EM, which is the unit /Widths is")
    add("// written in (PDF 1.7 Table 8.27).  A font with no /Widths - and a document relying on one of")
    add("// these fourteen has none - is answered out of here, because the metrics are the FORMAT's own")
    add("// data and no API on this release hands them over: CGFontCreateWithFontName answers 43.2070 for")
    add("// \"page 1\" in Courier where the host answers 43.2000, measured.")
    add("//")
    add("// The numbers were MEASURED, one character at a time, over make-font-fixtures.py's base-fourteen")
    add("// fixtures; facts/PDFKit/Selection11.md names the run.  Codes 32..126 only: the fixtures draw")
    add("// those and no others, so a code outside the span has no width here and the reader below says so")
    add("// rather than reaching past the end of the row.")
    add("//")
    add("// Symbol and ZapfDingbats read ZERO for almost every code, and that is measured rather than a")
    add("// gap: their built-in encodings are not WinAnsi, so a code written for another face resolves to no")
    add("// glyph in them.  Code 32 is the exception - 250 for Symbol, 278 for ZapfDingbats - because the")
    add("// space is the one code that resolves in every one of the fourteen.")
    add("")
    add("typedef struct {")
    add("    const char *name;")
    add(string.format("    short widths[%d];   // code - 32", LAST_CODE - FIRST_CODE + 1))
    add("    // THE FACE'S OWN DESCENT, in thousandths of an em and NEGATIVE, which is the other half")
    add("    // of Annex F's data this port needs: it is what puts the BOTTOM of a rect, and a document")
    add("    // relying on a standard font often carries no /FontDescriptor to read one from.  Measured")
    add("    // per face over the -descent fixtures, not transcribed - Courier answers 246 where a")
    add("    // published AFM table says 157, so the measurement is what goes in.")
    add("    //    A FLOAT and not a short, at the measurement's own precision: Helvetica's is")
    add("    //    -229.9833 and not -230, and rounding it to -230 moves every rect built from it by")
    add("    //    0.0002pt - which is the difference between 717.2400 and the host's 717.2402 on every")
    add("    //    fixture make-object-fixtures.py writes.")
    add("    float descent;")
    add("} CharonBase14Face;")
    add("")
    for _, face in ipairs(FACES) do
        local stem = face:lower()
        local row = widths[stem] or {}
        local space = spaces[stem]
        if space == nil then
            raise(face .. ": no -space fixture in the run output")
        end
        local values = {}
        for code = FIRST_CODE, LAST_CODE do
            if code == FIRST_CODE then
                values[#values + 1] = tostring(round_half_even(space))
            elseif row[code] ~= nil then
                values[#values + 1] = tostring(round_half_even(row[code]))
            else
                raise(string.format("%s: code %d was not measured", face, code))
            end
        end
        if descents[stem] == nil then
            raise(face .. ": no -descent fixture in the run output")
        end
        add(string.format('static const CharonBase14Face kCharonBase14_%s = { "%s", {',
            stem:gsub("%-", "_"), face))
        for i = 1, #values, 16 do
            local chunk = {}
            for j = i, math.min(i + 15, #values) do
                chunk[#chunk + 1] = values[j]
            end
            add("    " .. table.concat(chunk, ", ") .. ",")
        end
        add(string.format("}, %.4f };", descents[stem]))
        add("")
    end
    add("static const CharonBase14Face *const kCharonBase14[] = {")
    for _, face in ipairs(FACES) do
        add(string.format("    &kCharonBase14_%s,", (face:lower():gsub("%-", "_"))))
    end
    add("};")
    add("")
    return table.concat(out, "\n") .. "\n"
end

local function strip_newlines(text)
    return (text:gsub("\n+$", ""))
end

function main(...)
    local args, check = {}, false
    for _, arg in ipairs({ ... }) do
        if arg == "--check" then
            check = true
        else
            args[#args + 1] = arg
        end
    end
    -- ONE argument is the out.c alone, and the measurement defaults; TWO are the measurement and the out.c.
    if #args == 1 then
        table.insert(args, 1, path.join(os.scriptdir(), "base14-measurement.txt"))
    end
    if #args ~= 2 then
        raise("usage: make-base14-table.lua [<host-base14 output>] <out.c> [--check]")
    end
    if not file_exists(args[1]) then
        raise("no measurement at " .. args[1] .. "; it is committed beside this tool, and the command that produces it is in"
            .. " the header of that file")
    end
    local table_text = emit(read(args[1]), read_spaces(args[1]), read_descents(args[1], 720.0, 12.0))
    if check then
        -- The GENERATED SECTION of the file, not the whole of it: the file has a hand-written header above the GENERATED
        -- marker and the two class methods below it.
        local written = read_text(args[2])
        local start = written:find(GENERATED_MARKER, 1, true)
        local stop = written:find(FOOTER_MARKER, 1, true)
        if not start or not stop or stop < start then
            print("DIFFER: " .. args[2] .. " carries neither the '" .. GENERATED_MARKER .. "' marker nor the '"
                .. FOOTER_MARKER .. "' one, so the generated section cannot be located in it")
            os.exit(1)
        end
        local section = strip_newlines(written:sub(start, stop - 1))
        if section ~= strip_newlines(table_text) then
            print("DIFFER: the generated section of " .. args[2] .. " is not what this measurement produces,"
                .. " and it was read from " .. args[1])
            os.exit(1)
        end
        print("holds: the generated section of " .. args[2] .. " is exactly what " .. args[1] .. " produces")
        return
    end
    local handle = assert(io.open(args[2], "wb"))
    handle:write(table_text)
    handle:close()
    print("wrote " .. args[2] .. " from " .. args[1])
end
