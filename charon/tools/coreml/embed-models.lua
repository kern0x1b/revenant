-- embed-models.lua: the Core ML containers the device test carries, as a C header.
--   xmake l tools/coreml/embed-models.lua <model directory> <output header>
--
-- The device test has to run a real model, and a real model is a .mlmodel file. A test binary cannot open a
-- file on the developer's machine, so the containers tools/coreml/make-models.lua writes are embedded here, byte
-- for byte, with the name of each. Nothing is rebuilt here, so what the device reads is exactly what the host
-- differential and the interpreter check read.

-- The containers to carry, smallest first: a test binary is a release artefact and a model of a few hundred
-- bytes keeps it one. The GLM and the GLM classifier are enough to reach the reader, the description, a
-- prediction, the class labels and the probabilities.
local WANTED = {"glm", "glm_classifier", "tree_classifier", "nn_classifier"}

-- " 0x%02x," for every byte, a line break and three spaces after each sixteen.
local function escape(data)
    local out = {}
    for index = 1, #data do
        if index > 1 and (index - 1) % 16 == 0 then
            table.insert(out, "\n   ")
        end
        table.insert(out, string.format(" 0x%02x,", data:byte(index)))
    end
    return table.concat(out)
end

function main(models, out)
    local written = {}
    local lines = {
        "/* Generated by tools/coreml/embed-models.lua from the containers",
        " * tools/coreml/make-models.lua writes. Do not edit by hand: run the generator and read the",
        " * diff. The bytes are the CoreML specification's own message, so what the device reads is what",
        " * the host differential and the interpreter check read. */",
        "#ifndef CHARON_COREML_MODELS_H\n#define CHARON_COREML_MODELS_H\n",
    }
    for _, name in ipairs(WANTED) do
        local file = path.join(models, name .. ".mlmodel")
        if os.isfile(file) then
            local data = io.readfile(file, {encoding = "binary"})
            local guard = "charon_ml_model_" .. name
            table.insert(lines, string.format("static const unsigned char %s[] = {%s\n};\n", guard, escape(data)))
            table.insert(written, {name = name, guard = guard, length = #data})
        end
    end
    table.insert(lines, "typedef struct {\n"
        .. "    const char *name;\n"
        .. "    const unsigned char *bytes;\n"
        .. "    unsigned long length;\n"
        .. "} charon_ml_embedded_model;\n")
    table.insert(lines, "static const charon_ml_embedded_model charon_ml_embedded_models[] = {")
    for _, w in ipairs(written) do
        table.insert(lines, string.format('    { "%s", %s, %dul },', w.name, w.guard, w.length))
    end
    table.insert(lines, "    { 0, 0, 0 }\n};\n\n#endif /* CHARON_COREML_MODELS_H */")
    io.writefile(out, table.concat(lines, "\n") .. "\n", {encoding = "binary"})
    for _, w in ipairs(written) do
        print(string.format("embedded %s: %d bytes", w.name, w.length))
    end
    if #written == 0 then
        raise("no containers in %s: run tools/coreml/make-models.lua --out %s first", models, models)
    end
end
