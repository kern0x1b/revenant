local VERSION = "2"

local sdk = import("sdk", {anonymous = true})

local LAYOUT = {
    VERSION = VERSION,
    SOURCES_ROOT = "packages/a/apple-backports",
    SNAP_ROOT = "packages/a/apple-backports/spec",
    OUT_ROOT = "packages/a/apple-backports/.gen",
    PINS_ROOT = "packages/a/apple-backports/overrides/hashes",
    PROTOCOL_SETS_ROOT = "packages/a/apple-backports/overrides/protocol-sets",
    REGISTRY = "packages/a/apple-backports/registry",
    MARK = "// GENERATED by tools/gen.lua version " .. VERSION .. ". Do not edit. Regenerate: xmake l tools/gen.lua gen.",
    SHARD_FILE = "declarations.tsv",
    SPEC_COLUMNS = {"kind", "api", "cls", "key", "introduced", "type", "availability", "hash", "value_status", "value",
                    "host_value", "value_source", "owned", "tbd", "shape", "measured"},
    PIN_COLUMNS = {"api", "key", "pinned", "pinned-by", "registry"},
}

-- The constants of the layout: the version of the generator's output, the snapshot's identifiers and folders, the column lists.
function constants()
    return LAYOUT
end

-- The committed inputs of a framework live under snap_dir: its declaration shard (spec/<F>/declarations.tsv, whose member rows
-- carry each declaration hash). A nested framework's shard is spec/<Outer>/<Inner>/declarations.tsv, so F is "Outer/Inner".
function snap_dir(tree, fw)
    return path.join(tree, LAYOUT.SNAP_ROOT, fw)
end

function shard_path(tree, fw)
    return path.join(snap_dir(tree, fw), LAYOUT.SHARD_FILE)
end

-- The constant record of a framework: constants.tsv under snap_dir, one row per measured constant (the host-oracle values the shards
-- do not carry), with the declaration hash each row was recorded against. It is committed as data and changed only through the
-- refusal of gen (gen --record re-records it), the same discipline as the pins (design-spec-driven.md, "Records").
function constant_record_path(tree, fw)
    return path.join(snap_dir(tree, fw), "constants.tsv")
end

-- The build directory of a framework: every file the generator emits, the spec and the members listing and the manifest included.
-- Gitignored, never committed, and built from the committed inputs alone.
function gen_dir(tree, fw)
    return path.join(tree, LAYOUT.OUT_ROOT, fw)
end

-- The spec table the generator builds in memory from the shard and the constant record, written under gen_dir. sdk_release is the
-- SDK's version (sdk.discover), which names the file (sdk.names).
function spec_path(tree, fw, sdk_release)
    return path.join(gen_dir(tree, fw), "spec." .. sdk.names(sdk_release).sdk_id .. ".tsv")
end

-- The pin sidecar of a framework: the declaration hash each override-backed member was reviewed against (committed).
function pins_path(tree, fw)
    return path.join(tree, LAYOUT.PINS_ROOT, fw .. ".tsv")
end

-- The reviewed protocol set of a framework: the objc protocols whose objects the generator emits (one row per protocol). A
-- framework with no file has the empty set.
function protocol_set_path(tree, fw)
    return path.join(tree, LAYOUT.PROTOCOL_SETS_ROOT, fw .. ".tsv")
end

function manifest_path(tree, fw)
    return path.join(gen_dir(tree, fw), "manifest.tsv")
end

function members_path(tree, fw)
    return path.join(gen_dir(tree, fw), "members.tsv")
end

-- The registry rows of a framework: registry/<F>/*.json, as paths relative to the tree (the form pins and reports name them).
function registry_dir(fw)
    return path.join(LAYOUT.REGISTRY, fw)
end
