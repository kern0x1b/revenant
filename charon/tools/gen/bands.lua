-- The band objects of a framework whose spec is committed: spec/<F>/bands.json, read by gen and written, one file per band tag, into
-- .gen/<F>/ beside the spec-derived objects. It replaces tools/corpus/gen-ledger-objects.py, which wrote the same objects from the same
-- spec. A piece records its corpus rank in the spec, so the objects read no file outside the repository.
--
-- A piece is one of three kinds. A class (kind "class") is an @implementation the band declares; a category ("category") is an
-- @implementation of a class another object defines, the only way a later band extends an earlier one; a policy ("policy") emits no
-- @implementation at all and carries the names and rules of a class the package already defines. The spec states what each piece
-- forbids as well as what it carries, and the object says so in its header.
--
-- Refused, not written: a class (kind "class") that a committed .m of the package already defines. Two objects defining one class are a
-- duplicate class symbol at load, so the generator names the file that has it and stops.
--
-- Run through gen: xmake l tools/gen.lua gen --tree <tree> --framework FileProvider --sdk <iPhoneOS SDK> (the package build runs gen --all).

local json = import("core.base.json")
local files = import("files", {anonymous = true})
local layout = import("layout", {anonymous = true})

-- The spec's file name under the framework's snapshot folder (spec/<F>/bands.json).
local SPEC_NAME = "bands.json"

-- The header of a piece: its imports, its runtime header, and the note that says what the piece carries and forbids. The text is the one
-- the python wrote, with the producer line naming this module and the committed spec.
local function header_lines(piece, spec_rel)
    local lines = {"#import " .. piece.header}
    for _, extra in ipairs(piece.imports or {}) do
        table.insert(lines, "#import " .. extra)
    end
    local rank = piece.rank or ""
    local why = rank ~= "" and ("// Corpus rank " .. rank .. " of coordination/corpus/crash-demand-top.tsv. ") or ""
    table.insert(lines, "#import <objc/runtime.h>")
    table.insert(lines, "")
    table.insert(lines, "// The iOS " .. piece.band .. " band of this framework, generated by tools/gen/bands.lua from")
    table.insert(lines, "// " .. spec_rel .. ". " .. why .. "The spec is the whole of what this file is, and")
    table.insert(lines, "// it names what the file must NOT do as well as what it does, because inventing behaviour the")
    table.insert(lines, "// release cannot have is the whole risk in carrying a framework.")
    table.insert(lines, "")
    if piece.never_call ~= nil and #piece.never_call > 0 then
        table.insert(lines, "// CARRIED AND CALLABLE, and the differential must NOT call it: calling it on the host")
        table.insert(lines, "// asks this machine to mount a provider domain. The port carries it so an app does not")
        table.insert(lines, "// crash naming it; the harness never invokes it.")
        for _, name in ipairs(piece.never_call) do
            table.insert(lines, "//   never called: " .. name)
        end
        table.insert(lines, "")
    end
    if piece.carries ~= nil and #piece.carries > 0 then
        table.insert(lines, "// Carried surface, each entry one the corpus names:")
        for _, name in ipairs(piece.carries) do
            table.insert(lines, "//   " .. name)
        end
        table.insert(lines, "")
    end
    return lines
end

-- One piece's text: its header, then its body with the trailing whitespace off, then the final line feed.
local function piece_text(piece, spec_rel)
    local lines = header_lines(piece, spec_rel)
    table.insert(lines, (string.gsub(piece.body, "%s+$", "")))
    table.insert(lines, "")
    return table.concat(lines, "\n")
end

-- The class names the committed .m files of the package define, as an @implementation that is not a category: "@implementation X" and
-- "@implementation X : Super" and "@implementation X {" count, "@implementation X (Cat)" does not. The files named in own are left out.
local function defined_in_package(package_dir, own)
    local defined = {}
    for _, found in ipairs(files.glob(path.join(package_dir, "*.m"))) do
        local name = path.filename(found)
        if own[name] == nil then
            for line in io.lines(found) do
                local class, rest = string.match(line, "^@implementation%s+([%a_][%w_]*)(.*)$")
                if class ~= nil and (string.match(rest, "^%s*$") or string.match(rest, "^%s*:%s*[%a_][%w_]*%s*$")
                    or string.match(rest, "^%s*{")) then
                    defined[class] = defined[class] or {}
                    table.insert(defined[class], name)
                end
            end
        end
    end
    return defined
end

-- The pieces of each band, in the spec's order, and the band names in the spec's order. A band whose pieces name two tags is refused:
-- the tag names the file, so two tags would write two files for one band.
local function by_band(pieces)
    local bands, tags, order_of = {}, {}, {}
    for _, piece in ipairs(pieces) do
        local band = piece.band
        if bands[band] == nil then
            bands[band] = {}
            table.insert(order_of, band)
        end
        table.insert(bands[band], piece)
        tags[band] = tags[band] or {}
        tags[band][piece.tag] = true
    end
    for _, band in ipairs(order_of) do
        local count = 0
        for _ in pairs(tags[band]) do
            count = count + 1
        end
        assert(count == 1, string.format("band %s has more than one tag, so it would write more than one file", band))
    end
    return bands, order_of
end

-- The objects of a framework that its committed spec defines: name -> text, each name a file of .gen/<F>/. Empty for a framework with no
-- spec. Refused (raised) when a class piece names a class a committed .m of the package already defines.
function objects(tree, fw)
    local out = {}
    local spec_dir = layout.snap_dir(tree, fw)
    local text = files.read_text(path.join(spec_dir, SPEC_NAME))
    if text == nil then
        return out
    end
    local spec = json.decode(text)
    assert(spec.framework == fw, "the band spec of " .. fw .. " names " .. tostring(spec.framework))
    local spec_rel = path.relative(path.join(spec_dir, SPEC_NAME), tree)
    local prefix = spec.prefix or fw
    local own = {}
    for _, piece in ipairs(spec.pieces) do
        own[prefix .. piece.tag .. ".m"] = true
    end
    local package_dir = path.join(tree, layout.constants().SOURCES_ROOT, spec.package or fw)
    local defined = defined_in_package(package_dir, own)
    local clash = {}
    for _, piece in ipairs(spec.pieces) do
        local kind = piece.kind or "class"
        if kind ~= "policy" and kind ~= "category" and defined[piece.name] ~= nil then
            table.insert(clash, string.format("%s is already defined by %s", piece.name, table.concat(defined[piece.name], ", ")))
        end
    end
    if #clash > 0 then
        raise("the band spec of %s carries a class the package defines, and a second @implementation for one class is a duplicate class "
            .. "symbol at load: %s", fw, table.concat(clash, "; "))
    end
    local bands, band_order = by_band(spec.pieces)
    for _, band in ipairs(band_order) do
        local pieces = bands[band]
        local name = prefix .. pieces[1].tag .. ".m"
        local rendered = {}
        for _, piece in ipairs(pieces) do
            table.insert(rendered, piece_text(piece, spec_rel))
        end
        assert(out[name] == nil, "two bands name the object " .. name)
        out[name] = table.concat(rendered, "\n")
    end
    return out
end
