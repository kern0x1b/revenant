// Host differential: the same program is built against Apple's System (SDK) and against upstream's System
// built from the pinned 1.8.1 sources (module SystemUnderTest). Inputs come from a seeded generator; the seed is printed.
#if OURS
import SystemUnderTest
#else
import System
#endif

struct SplitMix64 {
  var state: UInt64
  mutating func next() -> UInt64 {
    state &+= 0x9E37_79B9_7F4A_7C15
    var z = state
    z = (z ^ (z >> 30)) &* 0xBF58_476D_1CE4_E5B9
    z = (z ^ (z >> 27)) &* 0x94D0_49BB_1331_11EB
    return z ^ (z >> 31)
  }
  mutating func below(_ n: Int) -> Int { Int(next() % UInt64(n)) }
}

let args = CommandLine.arguments
let seed: UInt64 = args.count > 2 ? UInt64(args[2])! : 20261014
var rng = SplitMix64(state: seed)
let runDir = args[1]
print("seed: \(seed)")

// FilePath: generated strings over an alphabet that includes separators, dots and a non-ASCII letter.
let alphabet = ["a", "b", ".", "/", "..", " ", "\u{E9}", "x.y", "//", "name.ext"]
func randomPath() -> String {
  var s = rng.below(3) == 0 ? "/" : ""
  for _ in 0..<(1 + rng.below(6)) { s += alphabet[rng.below(alphabet.count)] }
  return s
}
for i in 0..<300 {
  let s = randomPath()
  let p = FilePath(s)
  let comps = p.components.map { $0.string }
  print("path[\(i)] \(s.debugDescription) desc=\(p.description.debugDescription) abs=\(p.isAbsolute) root=\(p.root?.string ?? "nil") count=\(p.components.count) comps=\(comps) last=\(p.lastComponent?.string ?? "nil") ext=\(p.extension ?? "nil") stem=\(p.stem ?? "nil")")
  print("  norm=\(p.lexicallyNormalized().description.debugDescription) removed=\(p.removingLastComponent().description.debugDescription) appended=\(p.appending("c").description.debugDescription) pendingAdd=\((p.appending("/d")).description.debugDescription)")
}

// Errno: every raw value the test reaches, and the equality the module declares.
for raw in Int32(0)...140 {
  let e = Errno(rawValue: raw)
  print("errno[\(raw)] \(e.rawValue) \(e == .resourceTemporarilyUnavailable) \(e == .wouldBlock)")
}
print("errno consts: \(Errno.noSuchFileOrDirectory.rawValue) \(Errno.permissionDenied.rawValue) \(Errno.badFileDescriptor.rawValue) \(Errno.fileExists.rawValue)")

// FileDescriptor: write generated bytes to files in the run directory, read them back by seeking.
for i in 0..<20 {
  let name = "\(runDir)/fd-\(seed)-\(i).bin"
  let size = 1 + rng.below(4096)
  var bytes = [UInt8](repeating: 0, count: size)
  for j in 0..<size { bytes[j] = UInt8(truncatingIfNeeded: rng.next()) }
  do {
    let fd = try FileDescriptor.open(name, .writeOnly, options: [.create, .truncate], permissions: .ownerReadWrite)
    let written = try bytes.withUnsafeBytes { try fd.write($0) }
    try fd.close()
    let rd = try FileDescriptor.open(name, .readOnly)
    var back = [UInt8](repeating: 0, count: size + 8)
    let got = try back.withUnsafeMutableBytes { try rd.read(into: $0) }
    let at = try rd.seek(offset: Int64(size / 2), from: .start)
    var tail = [UInt8](repeating: 0, count: 4)
    let tailGot = try tail.withUnsafeMutableBytes { try rd.read(fromAbsoluteOffset: Int64(size / 2), into: $0) }
    try rd.close()
    print("fd[\(i)] size=\(size) written=\(written) got=\(got) equal=\(Array(back[0..<got]) == bytes) seekTo=\(at) tailGot=\(tailGot) tailEqual=\(Array(tail[0..<tailGot]) == Array(bytes[(size / 2)..<(size / 2 + tailGot)]))")
  } catch {
    print("fd[\(i)] error \(error)")
  }
}
do {
  _ = try FileDescriptor.open("\(runDir)/missing-\(seed).bin", .readOnly)
  print("missing: opened")
} catch let e as Errno {
  print("missing: errno \(e.rawValue) \(e == .noSuchFileOrDirectory)")
}

// Permissions: generated 9-bit modes and their set operations.
for i in 0..<64 {
  let raw = UInt16(truncatingIfNeeded: rng.next()) & 0o777
  let perm = FilePermissions(rawValue: raw)
  print("perm[\(i)] raw=\(raw) rawValue=\(perm.rawValue) ownerRead=\(perm.contains(.ownerRead)) groupWrite=\(perm.contains(.groupWrite)) otherExecute=\(perm.contains(.otherExecute)) union=\(perm.union(.ownerExecute).rawValue) minus=\(perm.subtracting(.ownerRead).rawValue)")
}
print("done")

// One line per carried row (rows.swift, constants.swift).
runRows(seed: seed, runDir: runDir)
