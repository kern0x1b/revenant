set_project("emulatorconnect")
set_version("0.0.1")
local root = os.getenv("REVENANT_ROOT") or path.join(os.scriptdir(), "../../../..")
add_repositories("revenant " .. root)
add_addons("revenant", {sourcedir = path.join(root, "toolchain")})
add_requires("revenant@swift-runtime", {alias = "swift-runtime"})
add_requires("revenant@libcxx", {alias = "libcxx"})
add_requires("revenant@network", {alias = "network"})
set_config("apple_minimum", "6.0")
includes("@addon/revenant/apple-ios")
includes("@addon/revenant/emulate")
set_allowedplats("iphoneos")
set_allowedarchs("iphoneos|armv7")
set_defaultplat("iphoneos")
set_defaultarchs("iphoneos|armv7")

target("emulatorconnect")
    add_rules("@addon/revenant/daemon")
    add_files("connect_writable.c")
    set_values("revenant.version", "1.0")
    set_values("revenant.control", "control")

target("emulatorconnect64")
    add_rules("@addon/revenant/daemon")
    add_files("connect_kevent64.c")
    set_values("revenant.version", "1.0")
    set_values("revenant.control", "control64")

target("emulatorconnectext")
    add_rules("@addon/revenant/daemon")
    add_files("connect_external.c")
    set_values("revenant.version", "1.0")
    set_values("revenant.control", "controlext")

target("emulatorconnectbackport")
    add_rules("@addon/revenant/daemon", "@addon/revenant/swift")
    add_files("main.swift")
    add_packages("network")
    set_values("revenant.version", "1.0")
    set_values("revenant.control", "controlbackport")

target("emulatortlsbackport")
    add_rules("@addon/revenant/daemon", "@addon/revenant/swift")
    add_files("tls.swift")
    add_packages("network")
    set_values("revenant.version", "1.0")
    set_values("revenant.control", "controltls")
    set_values("revenant.libraries", "network")
    local platform = path.join(root, "build", "iphoneos", "armv7", "release")
    set_values("revenant.platform", path.join(platform, "libNetworkBackports.dylib"), path.join(platform, "libSecurityBackports.dylib"))
