[[nodiscard]] constexpr const MemberDescriptor* find_member(
    std::string_view name)
{
    for (const auto& member : members) {
        if (member.name == name)
            return &member;
    }
    return nullptr;
}

[[nodiscard]] constexpr bool is_covered(std::string_view name)
{
    const auto* member = find_member(name);
    return member != nullptr &&
           (member->coverage == Coverage::saved ||
               member->coverage == Coverage::wired);
}

template <typename Names>
[[nodiscard]] std::optional<std::string_view> first_uncovered(
    const Names& names)
{
    for (const auto& name : names) {
        const std::string_view view { name };
        if (!is_covered(view))
            return view;
    }
    return std::nullopt;
}

[[nodiscard]] constexpr std::size_t count_of(Coverage coverage)
{
    std::size_t count { };
    for (const auto& member : members) {
        if (member.coverage == coverage)
            ++count;
    }
    return count;
}

