package("expo-font")
    set_kind("library", {headeronly = true})
    set_homepage("https://docs.expo.dev/versions/latest/sdk/font/")
    set_description("expo-font 57.0.4, the font loader of the Expo SDK, from its npm tarball: the Swift sources of its iOS half, patched to run on iOS 6 (the font descriptors through the CoreText backport, the render color as a UIColor instead of a SwiftUI Color)")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://registry.npmjs.org/expo-font/-/expo-font-$(version).tgz")
    add_versions("57.0.4", "a0c31613129a759ed77313e1fb28bf3645a550e4752042693c6729c39737e00e")
    add_patches("57.0.4", path.join(os.scriptdir(), "patches", "fontutils-ios6.patch"), "93aa0e0af846a4f545a5cc1129406585371e43661d962263e5c6bc83aa2b212c")
    add_configs("revision", {description = "Raised when the install script changes, since the script is not part of the install path.", default = "1", readonly = true})

    on_install(function (package)
        os.cp("*", package:installdir() .. "/")
    end)

    on_test(function (package)
        local json = import("core.base.json")
        local manifest = json.decode(io.readfile(path.join(package:installdir(), "package.json")))
        assert(manifest.name == "expo-font" and manifest.version == "57.0.4", "the package is " .. manifest.name .. " " .. manifest.version)
        local utils = io.readfile(path.join(package:installdir(), "ios", "FontUtils.swift"))
        assert(utils:find("revenantCTFontManagerCreateFontDescriptorsFromURL", 1, true), "the patch is not in the installed sources")
        assert(not utils:find("= CTFontManagerCreateFontDescriptorsFromURL(", 1, true), "the iOS 7 call is still in the installed sources")
        local records = io.readfile(path.join(package:installdir(), "ios", "FontUtilsRecords.swift"))
        assert(not records:find("import SwiftUI", 1, true), "the SwiftUI import is still in the installed sources")
    end)
