package("expo-sharing")
    set_kind("library", {headeronly = true})
    set_homepage("https://docs.expo.dev/versions/latest/sdk/sharing/")
    set_description("expo-sharing 57.0.23, the sharing of the Expo SDK, from its npm tarball: the Swift sources of its iOS half, patched for iOS 6 (the URL content details by NSURLConnection, the activity completion handler and the iPad popover of iOS 6, and the share-into payloads without JSONDecoder)")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://registry.npmjs.org/expo-sharing/-/expo-sharing-$(version).tgz")
    add_versions("57.0.23", "d4459cd20f359284b3d2dcc3e1b564720bcc76ae5ead1d313c058b26b12cea9a")
    add_patches("57.0.23", path.join(os.scriptdir(), "patches", "sharing-module-ios6.patch"), "b0063174bbdfff6dfa5fd0964eb6d0a6d98a5c5550fef9b289d7b975d4b479aa")
    add_patches("57.0.23", path.join(os.scriptdir(), "patches", "url-details-ios6.patch"), "1a7b26763687afd569f802ca88b117252718a55096bf6a7cd25467bd0bcffeb4")
    add_configs("revision", {description = "Raised when the install script changes, since the script is not part of the install path.", default = "1", readonly = true})

    on_install(function (package)
        os.cp("*", package:installdir() .. "/")
    end)

    on_test(function (package)
        local json = import("core.base.json")
        local manifest = json.decode(io.readfile(path.join(package:installdir(), "package.json")))
        assert(manifest.name == "expo-sharing" and manifest.version == "57.0.23", "the package is " .. manifest.name .. " " .. manifest.version)
        local details = io.readfile(path.join(package:installdir(), "ios", "ResolveUrlContentDetails.swift"))
        assert(not details:find("URLSession.shared.bytes", 1, true), "URLSession.bytes is still in the installed sources")
        assert(details:find("NSURLConnection", 1, true), "the header probe is not in the installed sources")
        local module = io.readfile(path.join(package:installdir(), "ios", "SharingModule.swift"))
        assert(not module:find("JSONDecoder", 1, true), "JSONDecoder is still in the installed sources")
        assert(module:find("UIPopoverController(contentViewController:", 1, true), "the iOS 6 popover is not in the installed sources")
    end)
