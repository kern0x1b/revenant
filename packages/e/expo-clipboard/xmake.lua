package("expo-clipboard")
    set_kind("library", {headeronly = true})
    set_homepage("https://docs.expo.dev/versions/latest/sdk/clipboard/")
    set_description("expo-clipboard 57.0.2, the clipboard of the Expo SDK, from its npm tarball: the Swift sources of its iOS half, patched to run on iOS 6 (without the iOS 16 paste button view, which UIPasteControl provides and iOS 6 does not have)")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://registry.npmjs.org/expo-clipboard/-/expo-clipboard-$(version).tgz")
    add_versions("57.0.2", "a0a1645d8368b56f7ffa36eca5b27f130c46f27e394e00a226296fadea935c9a")
    add_patches("57.0.2", path.join(os.scriptdir(), "patches", "clipboard-ios16.patch"), "047625792c56aa76eb3d9fbfe4a7ac98e74f410d221a0d00b7053de7d46abea8")
    add_configs("revision", {description = "Raised when the install script changes, since the script is not part of the install path.", default = "1", readonly = true})

    on_install(function (package)
        os.cp("*", package:installdir() .. "/")
    end)

    on_test(function (package)
        local json = import("core.base.json")
        local manifest = json.decode(io.readfile(path.join(package:installdir(), "package.json")))
        assert(manifest.name == "expo-clipboard" and manifest.version == "57.0.2", "the package is " .. manifest.name .. " " .. manifest.version)
        assert(not os.isfile(path.join(package:installdir(), "ios", "ClipboardPasteButton.swift")), "the iOS 16 paste button is still in the installed sources")
        local module = io.readfile(path.join(package:installdir(), "ios", "ClipboardModule.swift"))
        assert(not module:find("View(ClipboardPasteButton.self)", 1, true), "the paste button view is still registered")
    end)
