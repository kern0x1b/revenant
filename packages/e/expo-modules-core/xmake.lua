package("expo-modules-core")
    set_kind("library", {headeronly = true})
    set_homepage("https://docs.expo.dev/modules")
    set_description("expo-modules-core 57.0.23, the core of the Expo module system, from its npm tarball: the Swift, Objective-C and C++ sources of its iOS half, with the iOS 6 patches applied, among them the URL argument conversion without URLComponents on iOS 15 and lower")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://registry.npmjs.org/expo-modules-core/-/expo-modules-core-$(version).tgz")
    add_versions("57.0.23", "8aeb67ba47e385205a59f087485c9391828ed3eb2fb7db3ec1b0ef733ccf9298")
    add_patches("57.0.23", path.join(os.scriptdir(), "patches", "expo-fabric-view-swift-base.patch"), "124430698c9bc3d7166a5a596c502492da280cb4905b6a0ccc9fa41fbd77aa32")
    add_patches("57.0.23", path.join(os.scriptdir(), "patches", "expo-viewmodulewrapper-ios6.patch"), "7d396ad7f533b4f0ea4106b13def8092ecaed1782e8a0bc243e1d694f99051b8")
    add_patches("57.0.23", path.join(os.scriptdir(), "patches", "url-convert-ios6.patch"), "cb67c4e143441dad0171ee3bedab11778d489bd2bec34436e113eeabfbe8c8d0")
    add_configs("revision", {description = "Raised when the install script changes, since the script is not part of the install path.", default = "1", readonly = true})

    on_install(function (package)
        os.cp("*", package:installdir() .. "/")
    end)

    on_test(function (package)
        local json = import("core.base.json")
        local manifest = json.decode(io.readfile(path.join(package:installdir(), "package.json")))
        assert(manifest.name == "expo-modules-core" and manifest.version == "57.0.23", "the package is " .. manifest.name .. " " .. manifest.version)
        assert(os.isfile(path.join(package:installdir(), "ios/Fabric/ExpoFabricViewObjC.mm")), "ios/Fabric/ExpoFabricViewObjC.mm is not installed")
        local patched = io.readfile(path.join(package:installdir(), "ios/Fabric/ExpoFabricViewObjC.mm"))
        assert(patched:find("ViewManagerAdapter_", 1, true), "the patches are not in the installed sources")
        local utilities = io.readfile(path.join(package:installdir(), "ios/Utilities/Utilities.swift"))
        assert(not utilities:find(": URLComponents(string: value)?.url ?? URL(string: value)", 1, true), "URLComponents is still in the iOS 15 URL conversion")
    end)
