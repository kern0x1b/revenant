package("expo-notifications")
    set_kind("library", {headeronly = true})
    set_homepage("https://github.com/expo/expo/tree/main/packages/expo-notifications")
    set_description("expo-notifications 57.0.23, the Expo SDK local and push notifications over UserNotifications, from its npm tarball, patched to compile for iOS 6: the members newer than iOS 6 behind availability checks (the beacon UUID is proximityUUID before iOS 13, the critical sound needs iOS 12), the calendar trigger refused with an error before iOS 8, the iOS 26 repeated-day key left out")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://registry.npmjs.org/expo-notifications/-/expo-notifications-$(version).tgz")
    add_versions("57.0.23", "9739be2b4c6844d8a782a4572c6d47f838215afb15e04485262a9dbe4a4b521a")
    add_patches("57.0.23", path.join(os.scriptdir(), "patches", "notifications-ios6.patch"), "a9be19a8fca5a2d1057e15a73e3694378c55000f5c7c2acf00c855aedb266288")

    on_install(function (package)
        os.cp("*", package:installdir() .. "/")
    end)

    on_test(function (package)
        local json = import("core.base.json")
        local manifest = json.decode(io.readfile(path.join(package:installdir(), "package.json")))
        assert(manifest.name == "expo-notifications" and manifest.version == "57.0.23", "the package is " .. manifest.name .. " " .. manifest.version)
        assert(os.isfile(path.join(package:installdir(), "ios", "ExpoNotifications", "Notifications", "NotificationCenterManager.swift")), "expo-notifications has no notification center manager")
        assert(os.isfile(path.join(package:installdir(), "expo-module.config.json")), "expo-notifications has no expo-module.config.json")
        local triggers = io.readfile(path.join(package:installdir(), "ios", "ExpoNotifications", "Notifications", "TriggerRecords.swift"))
        assert(triggers:find("ERR_NOTIFICATIONS_CALENDAR_TRIGGER_UNSUPPORTED", 1, true), "the patch is not in the installed sources")
        local records = io.readfile(path.join(package:installdir(), "ios", "ExpoNotifications", "Notifications", "NotificationRecords.swift"))
        assert(records:find("proximityUUID", 1, true), "the patch is not in the installed sources")
    end)
