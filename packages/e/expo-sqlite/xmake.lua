package("expo-sqlite")
    set_kind("library", {headeronly = true})
    set_homepage("https://github.com/expo/expo/tree/main/packages/expo-sqlite")
    set_description("expo-sqlite 57.0.4, the Expo SDK SQLite database, from its npm tarball: the iOS module sources, and the SQLite amalgamation the default build vendors, patched to run on iOS 6 (removes SQLiteModuleLibSQL.swift which imports unavailable libsql module; default build uses vendored SQLite amalgamation)")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://registry.npmjs.org/expo-sqlite/-/expo-sqlite-$(version).tgz")
    add_versions("57.0.4", "da25d44a0d3e0ba70586a6a22ab61d2538924cb61d1569e99ffe142c859c249e")
    add_patches("57.0.4", path.join(os.scriptdir(), "patches", "sqlitemodulelibsql-remove.patch"), "c33cff784699edc49cc21a8be6559745256e474859379b29c94d9151dc61f3b7")

    on_install(function (package)
        os.cp("*", package:installdir() .. "/")
    end)

    on_test(function (package)
        local json = import("core.base.json")
        local manifest = json.decode(io.readfile(path.join(package:installdir(), "package.json")))
        assert(manifest.name == "expo-sqlite" and manifest.version == "57.0.4", "the package is " .. manifest.name .. " " .. manifest.version)
        assert(os.isdir(path.join(package:installdir(), "ios")), "expo-sqlite has no iOS sources")
        assert(os.isfile(path.join(package:installdir(), "expo-module.config.json")), "expo-sqlite has no expo-module.config.json")
        assert(not os.isfile(path.join(package:installdir(), "ios", "SQLiteModuleLibSQL.swift")), "SQLiteModuleLibSQL.swift should be removed")
        assert(os.isfile(path.join(package:installdir(), "ios", "SQLiteModule.swift")), "SQLiteModule.swift should be present")
    end)
