package("expo-file-system")
    set_kind("library", {headeronly = true})
    set_homepage("https://docs.expo.dev/versions/latest/sdk/filesystem/")
    set_description("expo-file-system 57.0.7, the file system of the Expo SDK, from its npm tarball: the Swift and Objective-C sources of its iOS half, with the iOS 14 class gates removed and its file handles opened by path, so that they run on iOS 6")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://registry.npmjs.org/expo-file-system/-/expo-file-system-$(version).tgz")
    add_versions("57.0.7", "6e6c41298ef68fff2e894ca85517d8c494c40b16e5032501575769717b0a29a9")
    add_patches("57.0.7", path.join(os.scriptdir(), "patches", "file-system-ios6.patch"), "e8a21e0b924c67194335a52c043956b87e49335ceaceb67537e7dc6bf8cf3a1f")
    add_configs("revision", {description = "Raised when the install script changes, since the script is not part of the install path.", default = "1", readonly = true})

    on_install(function (package)
        os.cp("*", package:installdir() .. "/")
    end)

    on_test(function (package)
        local json = import("core.base.json")
        local manifest = json.decode(io.readfile(path.join(package:installdir(), "package.json")))
        assert(manifest.name == "expo-file-system" and manifest.version == "57.0.7", "the package is " .. manifest.name .. " " .. manifest.version)
        local handle = io.readfile(path.join(package:installdir(), "ios", "FileSystemFileHandle.swift"))
        assert(not handle:find("@available(iOS 14", 1, true), "the iOS 14 gate is still on FileSystemFileHandle")
        assert(not handle:find("FileHandle(forReadingFrom:", 1, true), "the file handle is still opened through the iOS 13 initialiser")
        local module = io.readfile(path.join(package:installdir(), "ios", "FileSystemModule.swift"))
        assert(not module:find("@available(iOS 14", 1, true), "the iOS 14 gate is still on FileSystemModule")
    end)
