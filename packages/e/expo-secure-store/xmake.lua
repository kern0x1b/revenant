package("expo-secure-store")
    set_kind("library", {headeronly = true})
    set_homepage("https://github.com/expo/expo/tree/main/packages/expo-secure-store")
    set_description("expo-secure-store 57.0.4, the Expo SDK keychain storage, from its npm tarball: the Swift sources of its iOS half over SecItem, without the LocalAuthentication, access-control and passcode-bound parts that iOS 6 lacks (they raise an exception that says so), so that they run on iOS 6")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://registry.npmjs.org/expo-secure-store/-/expo-secure-store-$(version).tgz")
    add_versions("57.0.4", "6342c7d7a091c60a6d63a18e9073bc1245ddc2f7e6e496aab42f2cf068ba88ce")
    add_patches("57.0.4", path.join(os.scriptdir(), "patches", "secure-store-ios6.patch"), "23603e1bed22467c1236854177608d2d0e5f3a1c000a255004804041379cfe99")

    on_install(function (package)
        os.cp("*", package:installdir() .. "/")
    end)

    on_test(function (package)
        local json = import("core.base.json")
        local manifest = json.decode(io.readfile(path.join(package:installdir(), "package.json")))
        assert(manifest.name == "expo-secure-store" and manifest.version == "57.0.4", "the package is " .. manifest.name .. " " .. manifest.version)
        assert(os.isfile(path.join(package:installdir(), "expo-module.config.json")), "expo-secure-store has no expo-module.config.json")
        local module = io.readfile(path.join(package:installdir(), "ios", "SecureStoreModule.swift"))
        assert(not module:find("LocalAuthentication", 1, true), "LocalAuthentication is still imported")
        assert(not module:find("SecAccessControlCreateWithFlags", 1, true), "the iOS 8 access control is still used")
    end)
