package("expo-glass-effect")
    set_kind("library", {headeronly = true})
    set_homepage("https://docs.expo.dev/versions/latest/sdk/glass-effect/")
    set_description("expo-glass-effect 57.0.4, the glass effect of the Expo SDK, from its npm tarball: the Swift sources of its iOS half, patched to compile for iOS 6 (the React import as the module's internal import, the corner radii of the iOS 26 branch left unapplied, the animation with an explicit duration)")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://registry.npmjs.org/expo-glass-effect/-/expo-glass-effect-$(version).tgz")
    add_versions("57.0.4", "b1a247580abc1752375d8a16e7a3a38330e6f4593a83d5289c911220590dd2ff")
    add_patches("57.0.4", path.join(os.scriptdir(), "patches", "glassview-ios6.patch"), "f692741f74bc47ad2a8545e49ae47f1ccc3e8517f38feb3c8d7ec9c71c7c4026")
    add_configs("revision", {description = "Raised when the install script changes, since the script is not part of the install path.", default = "1", readonly = true})

    on_install(function (package)
        os.cp("*", package:installdir() .. "/")
    end)

    on_test(function (package)
        local json = import("core.base.json")
        local manifest = json.decode(io.readfile(path.join(package:installdir(), "package.json")))
        assert(manifest.name == "expo-glass-effect" and manifest.version == "57.0.4", "the package is " .. manifest.name .. " " .. manifest.version)
        local view = io.readfile(path.join(package:installdir(), "ios", "GlassView.swift"))
        assert(view:find("internal import React", 1, true), "the patch is not in the installed sources")
        assert(view:find("withDuration: 0.3", 1, true), "the patch is not in the installed sources")
    end)
