package("react-native-webview")
    set_kind("library", {headeronly = true})
    set_homepage("https://github.com/react-native-webview/react-native-webview")
    set_description("react-native-webview 13.16.1 from its npm tarball: the native sources of RNCWebView with the iOS 6 32-bit patch applied")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://registry.npmjs.org/react-native-webview/-/react-native-webview-$(version).tgz")
    add_versions("13.16.1", "a8704699207c6fba6dc3dd18f020f579e2653916fdb8aaba5f7979936a137d39")
    add_patches("13.16.1", path.join(os.scriptdir(), "patches", "ios6-32bit.patch"), "e62e01785e82f4d068f11134929b722be17363c3aec046e0de6af9b8b37b6a2e")
    add_configs("revision", {description = "Raised when the install script changes, since the script is not part of the install path.", default = "1", readonly = true})

    on_install(function (package)
        os.cp("*", package:installdir() .. "/")
    end)

    on_test(function (package)
        local json = import("core.base.json")
        local manifest = json.decode(io.readfile(path.join(package:installdir(), "package.json")))
        assert(manifest.name == "react-native-webview" and manifest.version == "13.16.1", "the package is " .. manifest.name .. " " .. manifest.version)
        assert(os.isfile(path.join(package:installdir(), "apple/RNCWebView.mm")), "apple/RNCWebView.mm is not installed")
        local patched = io.readfile(path.join(package:installdir(), "apple/RNCWebView.mm"))
        assert(patched:find("(CGFloat)newViewProps.contentInset.top", 1, true), "the patches are not in the installed sources")
    end)
