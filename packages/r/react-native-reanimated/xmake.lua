package("react-native-reanimated")
    set_kind("library", {headeronly = true})
    set_homepage("https://docs.swmansion.com/react-native-reanimated")
    set_description("react-native-reanimated 4.5.5 from its npm tarball: the native sources with the iOS 6 32-bit patch applied")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://registry.npmjs.org/react-native-reanimated/-/react-native-reanimated-$(version).tgz")
    add_versions("4.5.5", "761827a6351612aabaafc25803d94036b30760ebdea534e2fdf7c3486be19246")
    add_patches("4.5.5", path.join(os.scriptdir(), "patches", "ios6-32bit.patch"), "84bfd4f5e616f3ccb8515408d46c2736ab27b8b3429d71316f6c091c5541963e")
    add_configs("revision", {description = "Raised when the install script changes, since the script is not part of the install path.", default = "1", readonly = true})

    on_install(function (package)
        os.cp("*", package:installdir() .. "/")
    end)

    on_test(function (package)
        local json = import("core.base.json")
        local manifest = json.decode(io.readfile(path.join(package:installdir(), "package.json")))
        assert(manifest.name == "react-native-reanimated" and manifest.version == "4.5.5", "the package is " .. manifest.name .. " " .. manifest.version)
        assert(os.isfile(path.join(package:installdir(), "apple/reanimated/apple/CSS/REACSSPlatformProps.mm")), "apple/reanimated/apple/CSS/REACSSPlatformProps.mm is not installed")
        local patched = io.readfile(path.join(package:installdir(), "apple/reanimated/apple/CSS/REACSSPlatformProps.mm"))
        assert(patched:find("(CGFloat)", 1, true), "the patches are not in the installed sources")
    end)
