package("wasm3")
    set_homepage("https://github.com/wasm3/wasm3")
    set_description("wasm3, the WebAssembly interpreter, as a static library: the compat dylib runs WebAssembly through it, since JavaScriptCore's WebAssembly is 64-bit only")
    set_license("MIT")
    set_policy("package.strict_compatibility", true)

    add_urls("https://github.com/wasm3/wasm3.git")
    add_versions("v0.9.1-beta.1", "ac3c1dd1386e83be7de548211efd02805eb1dcee")
    add_deps("cmake", "ninja", {kind = "binary"})
    add_links("m3")

    on_install("iphoneos", function (package)
        io.writefile("build-revenant/CMakeLists.txt", [[
cmake_minimum_required(VERSION 3.21)
project(wasm3 C)
set(CMAKE_C_STANDARD 99)
set(CMAKE_C_STANDARD_REQUIRED YES)
set(CMAKE_C_EXTENSIONS YES)
include(CheckCSourceCompiles)
check_c_source_compiles("static __thread int value; int main(void) { return value; }" M3_TOOLCHAIN_HAS_THREAD_LOCAL)
add_subdirectory(${WASM3_SOURCE} source)
if(NOT M3_TOOLCHAIN_HAS_THREAD_LOCAL)
    target_compile_definitions(m3 PRIVATE "M3_THREAD_LOCAL=" M3_HAS_THREAD_LOCAL=0)
endif()
file(GLOB M3_HEADERS ${WASM3_SOURCE}/*.h)
install(TARGETS m3 ARCHIVE DESTINATION lib)
install(FILES ${M3_HEADERS} DESTINATION include)
]])
        local cmake = import("apple.cmake", {rootdir = path.join(package:scriptdir(), "..", "..", "..", "toolchain", "modules"), anonymous = true})
        cmake.install(package, {"-DWASM3_SOURCE=" .. path.absolute("source")}, {sourcedir = "build-revenant", licenses = "LICENSE"})
    end)

    on_test(function (package)
        assert(os.isfile(path.join(package:installdir("lib"), "libm3.a")))
        assert(os.isfile(path.join(package:installdir("include"), "wasm3.h")))
    end)
